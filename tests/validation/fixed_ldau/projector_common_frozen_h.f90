! Source-connected Phase-P validation on one frozen, finite 18x18 operator.
!
! The same Hermitian H is supplied to the production KS eigenvector
! occupation routine and to the production RS `bands%calculate_moments`
! Green-function extractor.  H is constructed from a declared unitary and a
! nondegenerate spectrum, so its exact occupied projector is an independent
! closed-form oracle.  The fixed noncubic U/J potential is generated by the
! production Hubbard builder from a separate Hermitian seed density and is
! included exactly once in H.
program projector_common_frozen_h
   use precision_mod, only: rp
   use basis_mod, only: basis_init, nb, norb, lmax_basis
   use math_mod, only: init_math_operators, pi, simpson_m, hubbard_spectral_density_element
   use logger_mod, only: g_logger
   use mpi_mod, only: rank, numprocs, ierr, atoms_per_process, start_atom, end_atom, g2l_map, &
                      get_mpi_variables, parallel_context
   use control_mod, only: control
   use lattice_mod, only: lattice
   use charge_mod, only: charge
   use hamiltonian_mod, only: hamiltonian
   use energy_mod, only: energy
   use recursion_mod, only: recursion
   use density_of_states_mod, only: dos
   use green_mod, only: green
   use bands_mod, only: bands
   use reciprocal_mod, only: reciprocal
   use kpoint_workset_mod, only: kpoint_workset, make_kpoint_workset
#ifdef USE_MPI
   use mpi
#endif
   implicit none

   integer, parameter :: nk = 2, nch = 6000
   real(rp), parameter :: ef = 0.0_rp, eta = 0.004_rp, emin = -3.0_rp
   real(rp), parameter :: tol_ks = 5.0e-12_rp, tol_rs_quad = 1.0e-4_rp
   real(rp) :: weights(nk), qlerr, rs_quad_error, broadening_error
   real(rp) :: rs_vs_simpson, refinement_errors(4)
   integer :: refinement_meshes(4) = [750, 1500, 3000, 6000]
   real(rp) :: imag_coherence, v_imag, h_identity_error, h_hermiticity_error
   real(rp) :: ks_conjugate_mismatch, rs_transpose_mismatch
   integer :: local_nk, ik, spin, a, b, band, ie
   complex(rp), allocatable :: q(:, :), htarget(:, :), hbare(:, :), hcheck(:, :)
   complex(rp) :: projector_exact(5, 5, 2), projector_lorentz(5, 5, 2)
   complex(rp) :: projector_simpson(5, 5, 2)
   complex(rp) :: projector_ks(5, 5, 2), projector_rs(5, 5, 2), projector_wrong(5, 5, 2)
   complex(rp), allocatable :: gmat(:, :)
   real(rp), allocatable :: eig(:)
   real(rp) :: e, angle
   type(parallel_context) :: parallel
   type(control), target :: ctl
   type(lattice), target :: lat
   type(charge), target :: chg
   type(hamiltonian), target :: ham
   type(energy), target :: en
   type(recursion), target :: rec
   type(dos), target :: dos_state
   type(green), target :: gr
   type(bands) :: rs
   type(reciprocal) :: ks
   logical :: failed

   failed = .false.
#ifdef USE_MPI
   call MPI_INIT(ierr)
#endif
   parallel = parallel_context()
   call g_logger%init()
   call basis_init(2)
   call init_math_operators()
   call get_mpi_variables(rank, 1)
   allocate(q(nb,nb), htarget(nb,nb), hbare(nb,nb), hcheck(nb,nb), eig(nb))

   call setup_objects()
   call setup_common_operator()
   call setup_ks()

   call ks%calculate_ldm_from_projected_dos(lat, fixed_liechtenstein=.true.)
   call copy_d_density(lat, projector_ks)
   do spin = 1, 2
      qlerr = maxval(abs(projector_ks(:, :, spin) - projector_exact(:, :, spin)))
      if (qlerr > tol_ks) failed = .true.
   end do

   ! Negative control: conjugating every KS spinor reverses the imaginary
   ! projector coherences.  The production output must then disagree with the
   ! independent common-H projector by a large, measured margin.
   ks%eigenvectors = conjg(ks%eigenvectors)
   call ks%calculate_ldm_from_projected_dos(lat, fixed_liechtenstein=.true.)
   call copy_d_density(lat, projector_wrong)
   ks_conjugate_mismatch = maxval(abs(projector_wrong - projector_exact))
   if (ks_conjugate_mismatch < 0.1_rp) failed = .true.
   ks%eigenvectors = conjg(ks%eigenvectors)

   call setup_rs_green(.true.)
   call rs%calculate_moments()
   call copy_d_density(lat, projector_rs)
   call run_simpson_mesh_refinement(refinement_errors, projector_simpson)
   rs_quad_error = maxval(abs(projector_rs - projector_lorentz))
   rs_vs_simpson = maxval(abs(projector_rs - projector_simpson))
   broadening_error = maxval(abs(projector_lorentz - projector_exact))
   if (rs_quad_error > tol_rs_quad) failed = .true.
   if (rs_vs_simpson > 5.0e-12_rp) failed = .true.
   if (any(refinement_errors(2:4) >= refinement_errors(1:3))) failed = .true.
   if (refinement_errors(4) > tol_rs_quad) failed = .true.
   if (broadening_error <= rs_quad_error) failed = .true.

   imag_coherence = max(maxval(abs(aimag(projector_exact(:, :, 1)))), &
                        maxval(abs(aimag(projector_exact(:, :, 2)))))
   v_imag = maxval(abs(aimag(ham%hubbard_u_pot(:, :, 1))))
   if (imag_coherence < 1.0e-2_rp .or. v_imag < 1.0e-5_rp) failed = .true.

   ! Negative control on the RS spectral matrix: H^T has P^T and flips the
   ! complex orbital coherences while leaving the spectrum unchanged.
   call setup_rs_green(.false.)
   call rs%calculate_moments()
   call copy_d_density(lat, projector_wrong)
   rs_transpose_mismatch = maxval(abs(projector_wrong - projector_exact))
   if (rs_transpose_mismatch < 0.1_rp) failed = .true.

#ifdef USE_MPI
   call reduce_failure(failed)
#endif
   if (rank == 0) then
      write(*,'(a,es14.6)') 'KS max error vs exact frozen-H projector = ', &
         maxval(abs(projector_ks - projector_exact))
      write(*,'(a,es14.6)') 'RS max quadrature error vs finite-window Lorentz oracle = ', rs_quad_error
      write(*,'(a,es14.6)') 'RS production vs 6000-point Simpson reference = ', rs_vs_simpson
      do ik = 1, size(refinement_meshes)
         write(*,'(a,i0,a,es14.6)') 'Lorentz-oracle Simpson error nchannels=', refinement_meshes(ik), ' = ', refinement_errors(ik)
      end do
      write(*,'(a,es14.6)') 'RS broadening/window difference vs sharp KS projector = ', broadening_error
      write(*,'(a,es14.6)') 'max exact imaginary d coherence = ', imag_coherence
      write(*,'(a,es14.6)') 'max imaginary production V_U entry = ', v_imag
      write(*,'(a,es14.6)') 'max |(H0+V_U)-H| = ', h_identity_error
      write(*,'(a,es14.6)') 'max |H-H^dagger| = ', h_hermiticity_error
      write(*,'(a,es14.6)') 'KS conjugation negative-control mismatch = ', ks_conjugate_mismatch
      write(*,'(a,es14.6)') 'RS transpose negative-control mismatch = ', rs_transpose_mismatch
      if (failed) then
         write(*,'(a)') 'projector_common_frozen_h: FAIL'
      else
         write(*,'(a)') 'projector_common_frozen_h: PASS'
      end if
   end if
#ifdef USE_MPI
   call parallel%restore_to_default()
   call MPI_FINALIZE(ierr)
#endif
   if (failed) error stop 1

contains

   subroutine run_simpson_mesh_refinement(errors, finest_projector)
      real(rp), intent(out) :: errors(4)
      complex(rp), intent(out) :: finest_projector(5,5,2)
      real(rp), allocatable :: energy_mesh(:), y_real(:), y_imag(:)
      complex(rp) :: spectral, g_ab, g_ba
      complex(rp) :: integrated(5,5,2)
      real(rp) :: step, endpoint, egrid, value_real, value_imag
      integer :: level, nchan, npts, iorb_a, iorb_b, spin_id, spin_offset, row, col, band_id, ie

      finest_projector = cmplx(0.0_rp,0.0_rp,rp)
      do level = 1, size(refinement_meshes)
         nchan = refinement_meshes(level)
         step = (ef-emin)/real(nchan/2,rp)
         npts = nint((ef-emin)/step)
         endpoint = emin + real(npts-1,rp)*step
         allocate(energy_mesh(nchan+10), y_real(nchan+10), y_imag(nchan+10))
         do ie = 1, nchan+10
            energy_mesh(ie) = emin + real(ie-1,rp)*step
         end do
         integrated = cmplx(0.0_rp,0.0_rp,rp)
         do spin_id = 1, 2
            spin_offset = (spin_id-1)*norb
            do iorb_a = 1, 5
               row = spin_offset + 4 + iorb_a
               do iorb_b = 1, 5
                  col = spin_offset + 4 + iorb_b
                  do ie = 1, nchan+10
                     egrid = energy_mesh(ie)
                     spectral = cmplx(0.0_rp,0.0_rp,rp)
                     do band_id = 1, nb
                        g_ab = q(row,band_id)*conjg(q(col,band_id))/ &
                               cmplx(egrid-eig(band_id),eta,rp)
                        g_ba = q(col,band_id)*conjg(q(row,band_id))/ &
                               cmplx(egrid-eig(band_id),eta,rp)
                        spectral = spectral + hubbard_spectral_density_element(g_ab,g_ba)
                     end do
                     y_real(ie) = real(spectral,rp)
                     y_imag(ie) = aimag(spectral)
                  end do
                  call simpson_m(value_real,step,ef,npts,y_real,endpoint,0,energy_mesh)
                  call simpson_m(value_imag,step,ef,npts,y_imag,endpoint,0,energy_mesh)
                  integrated(iorb_a,iorb_b,spin_id) = cmplx(value_real,value_imag,rp)
               end do
            end do
         end do
         errors(level) = maxval(abs(integrated-projector_lorentz))
         if (level == size(refinement_meshes)) finest_projector = integrated
         deallocate(energy_mesh,y_real,y_imag)
      end do
   end subroutine run_simpson_mesh_refinement

   subroutine setup_objects()
      call ctl%restore_to_default()
      ctl%lmax = 2
      ctl%nsp = 1
      ctl%calctype = 'B'
      ctl%density_policy = 'relaxed_reference'

      lat%nrec = 1; lat%nbulk = 0; lat%nbulk_bulk = 1; lat%ntype = 1
      lat%nn_max = 1; lat%kk = 1; lat%nmax = 1; lat%alat = 1.0_rp
      lat%r2 = 1.0_rp; lat%a = 0.0_rp; lat%a(1,1) = 1.0_rp
      lat%a(2,2) = 1.0_rp; lat%a(3,3) = 1.0_rp
      lat%a_cart_inv = lat%a; lat%a_cart_inv_ready = .true.
      lat%control => ctl
      allocate(lat%ib(1), lat%atlist(1), lat%iz(1), lat%num(1), lat%nn(1,1), &
               lat%sbar(norb,norb,1,1), lat%symbolic_atoms(1))
      lat%ib = 1; lat%atlist = 1; lat%iz = 1; lat%num = 1; lat%nn = 1
      lat%sbar = cmplx(0.0_rp, 0.0_rp, rp)
      call lat%symbolic_atoms(1)%restore_to_default()
      lat%symbolic_atoms(1)%potential%hubbard_u(3) = 0.25_rp
      lat%symbolic_atoms(1)%potential%hubbard_j(3) = 0.04_rp
      lat%symbolic_atoms(1)%potential%mom = [0.0_rp, 0.0_rp, 1.0_rp]
      lat%symbolic_atoms(1)%potential%qpar = 1.0_rp
      lat%symbolic_atoms(1)%potential%srdel = 0.1_rp
      lat%symbolic_atoms(1)%potential%c = 0.0_rp
      lat%symbolic_atoms(1)%potential%gravity_center = 0.0_rp
      lat%symbolic_atoms(1)%potential%pl = 0.0_rp

      chg%lattice => lat
      chg%symbolic_atom => lat%symbolic_atoms
      ham%charge => chg; ham%lattice => lat; ham%control => ctl
      ham%local_axis = .false.
      ham%operator_generation = 0
      ham%hubbard_u_general_check = .true.
      ham%hubbard_u_potential_form = 'liechtenstein'
      ham%hubbard_u_sc_check = .false.; ham%hubbard_v_check = .false.
      allocate(ham%hubbard_u_pot(nb,nb,1))
      ham%hubbard_u_pot = cmplx(0.0_rp, 0.0_rp, rp)

      en%lattice => lat
      call en%restore_to_default()
      en%channels_ldos = nch
      en%energy_min = emin
      en%energy_max = 3.0_rp
      en%fermi = ef
      en%temperature = 0.0_rp
      call en%e_mesh()

      rec%hamiltonian => ham; rec%lattice => lat; rec%en => en; rec%control => ctl
      dos_state%recursion => rec; dos_state%en => en; dos_state%lattice => lat
      dos_state%control => ctl; dos_state%symbolic_atom => lat%symbolic_atoms
      gr%recursion => rec; gr%lattice => lat; gr%symbolic_atom => lat%symbolic_atoms
      gr%dos => dos_state; gr%control => ctl; gr%en => en
      allocate(gr%g0(nb,nb,nch+10,atoms_per_process))
      gr%g0 = cmplx(0.0_rp,0.0_rp,rp)

      rs%green => gr; rs%lattice => lat; rs%symbolic_atom => lat%symbolic_atoms
      rs%dos => dos_state; rs%en => en; rs%control => ctl; rs%recursion => rec
      call rs%restore_to_default()
      ! Mirror the production fixed-EF setup in bands.f90: NV1 is the grid
      ! index immediately below EF and E1 is that grid point; simpson_m adds
      ! the final partial interval to the requested Fermi endpoint.
      rs%nv1 = nint((en%fermi-en%energy_min)/en%edel)
      rs%e1 = en%energy_min + real(rs%nv1-1,rp)*en%edel
   end subroutine setup_objects

   subroutine setup_common_operator()
      integer :: i, j, k, spin_offset, row, col
      complex(rp) :: phase
      complex(rp) :: base_q(9,9), dmat(18,18)
      real(rp) :: occ

      ! Physical Hermitian seed P, with nonzero complex orbital coherences.
      do spin = 1, 2
         do i = 1, 5
            lat%symbolic_atoms(1)%potential%ldm(3,spin,i,i) = 0.15_rp + 0.07_rp*real(i,rp) + &
               0.02_rp*real(spin-1,rp)
            do j = i+1, 5
               phase = cmplx(0.008_rp*real(i+j,rp), 0.004_rp*real(i-j,rp), rp)
               lat%symbolic_atoms(1)%potential%ldm(3,spin,i,j) = phase
               lat%symbolic_atoms(1)%potential%ldm(3,spin,j,i) = conjg(phase)
            end do
         end do
      end do
      call ham%calculate_hubbard_u_potential_general()

      ! Known unitary diagonalizer. s/p remain unmixed; the d block is a
      ! complex discrete Fourier matrix and the unequal eigenvalues make H
      ! noncubic. This avoids using the production eigensolver in the oracle.
      base_q = cmplx(0.0_rp,0.0_rp,rp)
      do i = 1, 4
         base_q(i,i) = cmplx(1.0_rp,0.0_rp,rp)
      end do
      do i = 1, 5
         do j = 1, 5
            angle = 2.0_rp*pi*real((i-1)*(j-1),rp)/5.0_rp
            base_q(i+4,j+4) = cmplx(cos(angle),sin(angle),rp)/sqrt(5.0_rp)
         end do
      end do
      q = cmplx(0.0_rp,0.0_rp,rp)
      q(1:norb,1:norb) = base_q
      q(norb+1:nb,norb+1:nb) = base_q
      eig(1:4) = [-1.4_rp,-1.0_rp,-0.8_rp,-0.6_rp]
      eig(5:9) = [-0.34_rp,-0.19_rp,0.16_rp,0.39_rp,0.61_rp]
      eig(norb+1:norb+4) = [-1.3_rp,-0.9_rp,-0.7_rp,-0.5_rp]
      eig(norb+5:nb) = [-0.27_rp,-0.11_rp,0.23_rp,0.46_rp,0.72_rp]
      dmat = cmplx(0.0_rp,0.0_rp,rp)
      do i = 1, nb
         dmat(i,i) = cmplx(eig(i),0.0_rp,rp)
      end do
      htarget = matmul(q,matmul(dmat,transpose(conjg(q))))
      hbare = htarget - ham%hubbard_u_pot(:,:,1)
      hcheck = hbare + ham%hubbard_u_pot(:,:,1)
      h_identity_error = maxval(abs(hcheck - htarget))
      h_hermiticity_error = maxval(abs(htarget - transpose(conjg(htarget))))
      if (h_identity_error > 2.0e-14_rp .or. h_hermiticity_error > 2.0e-14_rp) failed = .true.

      projector_exact = cmplx(0.0_rp,0.0_rp,rp)
      projector_lorentz = cmplx(0.0_rp,0.0_rp,rp)
      do spin = 1, 2
         spin_offset = (spin-1)*norb
         do a = 1, 5
            row = spin_offset + 4 + a
            do b = 1, 5
               col = spin_offset + 4 + b
               do k = 1, nb
                  if (eig(k) < ef) then
                     projector_exact(a,b,spin) = projector_exact(a,b,spin) + q(row,k)*conjg(q(col,k))
                  end if
                  occ = (atan((ef-eig(k))/eta)-atan((emin-eig(k))/eta))/pi
                  projector_lorentz(a,b,spin) = projector_lorentz(a,b,spin) + &
                     occ*q(row,k)*conjg(q(col,k))
               end do
            end do
         end do
      end do
   end subroutine setup_common_operator

   subroutine setup_ks()
      real(rp) :: all_points(3,nk)
      type(kpoint_workset) :: workset

      all_points = 0.0_rp
      weights = 1.0_rp/real(nk,rp)
      workset = make_kpoint_workset(all_points,weights,parallel,numprocs>1,.true.)
      local_nk = workset%nk_local
      ks%hamiltonian => ham; ks%lattice => lat; ks%control => ctl
      ks%n_spin_components = 2
      ks%nk_mesh = [nk, 1, 1]
      ks%nk_total = nk; ks%nk_local = local_nk
      ks%k_mesh_distributed_active = numprocs > 1
      ks%use_symmetry_reduction = .false.
      ks%temperature = 0.0_rp; ks%fermi_level = ef
      ks%k_workset = workset
      allocate(ks%eigenvalues(nb,local_nk),ks%eigenvectors(nb,nb,local_nk))
      allocate(ks%k_weights(nk),ks%k_l2g_map(local_nk),ks%k_g2l_map(nk))
      ks%k_weights = weights
      ks%k_points = all_points
      ks%k_l2g_map = workset%local_to_global
      ks%k_g2l_map = workset%global_to_local
      ks%cached_operator_generation = ham%operator_generation
      do ik = 1, local_nk
         ks%eigenvalues(:,ik) = eig
         ks%eigenvectors(:,:,ik) = q
      end do
   end subroutine setup_ks

   subroutine setup_rs_green(correct)
      logical, intent(in) :: correct
      integer :: local_atom, global_atom
      complex(rp) :: z

      if (allocated(gr%g0)) deallocate(gr%g0)
      allocate(gr%g0(nb,nb,nch+10,atoms_per_process))
      gr%g0 = cmplx(0.0_rp,0.0_rp,rp)
      if (start_atom > end_atom) return
      global_atom = start_atom
      local_atom = g2l_map(global_atom)
      if (allocated(gmat)) deallocate(gmat)
      allocate(gmat(nb,nb))
      do ie = 1, nch+10
         e = en%ene(ie)
         gmat = cmplx(0.0_rp,0.0_rp,rp)
         do band = 1, nb
            z = cmplx(e-eig(band),eta,rp)
            do a = 1, nb
               do b = 1, nb
                  if (correct) then
                     gmat(a,b) = gmat(a,b) + q(a,band)*conjg(q(b,band))/z
                  else
                     gmat(a,b) = gmat(a,b) + conjg(q(a,band))*q(b,band)/z
                  end if
               end do
            end do
         end do
         gr%g0(:,:,ie,local_atom) = gmat
      end do
   end subroutine setup_rs_green

   subroutine copy_d_density(lattice_obj, output)
      type(lattice), intent(in) :: lattice_obj
      complex(rp), intent(out) :: output(5,5,2)
      integer :: s
      do s = 1, 2
         output(:,:,s) = lattice_obj%symbolic_atoms(1)%potential%ldm(3,s,1:5,1:5)
      end do
   end subroutine copy_d_density

#ifdef USE_MPI
   subroutine reduce_failure(test_failed)
      logical, intent(inout) :: test_failed
      integer :: local_fail, global_fail
      local_fail = merge(1,0,test_failed)
      call MPI_ALLREDUCE(local_fail,global_fail,1,MPI_INTEGER,MPI_MAX,MPI_COMM_WORLD,ierr)
      test_failed = global_fail /= 0
   end subroutine reduce_failure
#endif

end program projector_common_frozen_h

! Source-connected Phase-P validation on a frozen two-site finite operator.
!
! The same Hermitian H is supplied to the production KS eigenvector
! occupation routine and to the production RS `bands%calculate_moments`
! Green-function extractor.  H is constructed from a declared unitary and a
! nondegenerate spectrum, so its exact occupied projector is an independent
! closed-form oracle.  The fixed noncubic U/J potential is generated by the
! production Hubbard builder from a separate Hermitian seed density and is
! included exactly once in H.
program projector_multisite_frozen_h
   use precision_mod, only: rp
   use basis_mod, only: basis_init, nb, norb, spin_off, lmax_basis
   use math_mod, only: init_math_operators, pi, simpson_m, hubbard_spectral_density_element, &
      correct_d_shell_moments, extract_hubbard_d_shell_potential
   use logger_mod, only: g_logger
   use mpi_mod, only: rank, numprocs, ierr, atoms_per_process, start_atom, end_atom, g2l_map, &
                      get_mpi_variables, parallel_context, assignment(=)
   use control_mod, only: control
   use lattice_mod, only: lattice
   use symbolic_atom_mod, only: symbolic_atom
   use charge_mod, only: charge
   use hamiltonian_mod, only: hamiltonian, rd1_vin_ok, rd1_vin_not_recursion_site, rd1_vin_duplicate, &
      rd1_vin_wrong_type, rd1_vin_missing_or_stale
   use energy_mod, only: energy
   use recursion_mod, only: recursion
   use density_of_states_mod, only: dos
   use green_mod, only: green
   use bands_mod, only: bands
   use reciprocal_mod, only: reciprocal
   use kpoint_workset_mod, only: kpoint_workset, make_kpoint_workset
#ifdef USE_MPI
   use mpi
#endif
   implicit none

   integer, parameter :: nk = 2, nch = 6000, nsites = 2
   real(rp), parameter :: ef = 0.0_rp, eta = 0.004_rp, emin = -3.0_rp
   real(rp), parameter :: tol_ks = 5.0e-12_rp, tol_rs_quad = 1.0e-4_rp
   ! Predeclared M1 limits: exact KS eigenpair sum 5e-12 Ry; RS uses
   ! the 1e-4 occupation budget times the 3 Ry maximum |E| in [-3,0] Ry.
   real(rp), parameter :: tol_ks_m1 = 5.0e-12_rp, tol_rs_m1 = 3.0e-4_rp
   ! The same-call trace identity uses identical production grids; the looser
   ! analytic-oracle budget above does not apply here.
   real(rp), parameter :: tol_trace_m1 = 1.0e-10_rp
   ! Wrong orientation/site map must exceed 10x the accepted RS M1 budget.
   real(rp), parameter :: tol_wrong_m1 = 3.0e-3_rp
   real(rp) :: weights(nk), qlerr, rs_quad_error, broadening_error
   real(rp) :: rs_vs_simpson, refinement_errors(4)
   real(rp) :: m1_refinement_errors(4), ks_m1_error, rs_m1_error, rs_m1_vs_simpson
   real(rp) :: ks_m1_trace_error, rs_m1_trace_error
   real(rp) :: ks_m1_conjugate_mismatch, rs_m1_transpose_mismatch
   real(rp) :: ks_m1_site_swap_mismatch, rs_m1_site_swap_mismatch
   integer :: refinement_meshes(4) = [750, 1500, 3000, 6000]
   real(rp) :: imag_coherence, v_imag, h_identity_error, h_hermiticity_error, site_swap_mismatch
   real(rp) :: ks_conjugate_mismatch, rs_transpose_mismatch
   real(rp) :: site_ks_error(nsites), site_rs_error(nsites), site_trace(nsites,2)
   integer :: local_nk, ik, spin, a, b, band, ie, isite
   complex(rp), allocatable :: q(:, :), htarget(:, :), hbare(:, :), hcheck(:, :), vglobal(:, :)
   complex(rp) :: projector_exact(5, 5, 2, nsites), projector_lorentz(5, 5, 2, nsites)
   complex(rp) :: projector_simpson(5, 5, 2, nsites)
   complex(rp) :: projector_ks(5, 5, 2, nsites), projector_rs(5, 5, 2, nsites), projector_wrong(5, 5, 2, nsites)
   complex(rp) :: m1_exact_ks(nsites,2,5,5), m1_exact_rs(nsites,2,5,5)
   complex(rp) :: m1_ks(nsites,4,2,7,7), m1_rs(nsites,4,2,7,7), m1_wrong(nsites,4,2,7,7)
   complex(rp) :: m1_simpson(nsites,2,5,5)
   complex(rp), allocatable :: gmat(:, :)
   real(rp), allocatable :: eig(:)
   real(rp) :: e, angle
   type(parallel_context) :: parallel
   type(control), target :: ctl
   type(lattice), target :: lat
   type(charge), target :: chg
   type(hamiltonian), target :: ham
   type(energy), target :: en
   type(recursion), target :: rec
   type(dos), target :: dos_state
   type(green), target :: gr
   type(bands) :: rs
   type(reciprocal) :: ks
   logical :: failed

   failed = .false.
#ifdef USE_MPI
   call MPI_INIT(ierr)
#endif
   parallel = parallel_context()
   call g_logger%init()
   call basis_init(2)
   call init_math_operators()
   call get_mpi_variables(rank, nsites)
   allocate(q(nsites*nb,nsites*nb), htarget(nsites*nb,nsites*nb), &
            hbare(nsites*nb,nsites*nb), hcheck(nsites*nb,nsites*nb), &
            vglobal(nsites*nb,nsites*nb), eig(nsites*nb))

   call setup_objects()
   call setup_common_operator()
   call setup_ks()

   m1_ks = cmplx(0.0_rp,0.0_rp,rp)
   call ks%calculate_ldm_from_projected_dos(lat, fixed_liechtenstein=.true., m1_out=m1_ks)
   ks_m1_error = 0.0_rp
   do isite = 1, nsites
      ks_m1_error = max(ks_m1_error, maxval(abs(m1_ks(isite,3,:,1:5,1:5)-m1_exact_ks(isite,:,:,:))))
   end do
   call ks%calculate_band_moments()
   ks_m1_trace_error = 0.0_rp
   do isite = 1, nsites
      do spin = 1, 2
         ks_m1_trace_error = max(ks_m1_trace_error, abs(real(sum([(m1_ks(isite,3,spin,a,a),a=1,5)]),rp) - &
            ks%band_moments(isite,3,spin,1)*ks%band_moments(isite,3,spin,2)))
      end do
   end do
   if (ks_m1_error > tol_ks_m1 .or. ks_m1_trace_error > tol_trace_m1) failed = .true.
   call copy_d_density(lat, 1, projector_ks(:, :, :, 1))
   call copy_d_density(lat, 2, projector_ks(:, :, :, 2))
   qlerr = 0.0_rp
   site_ks_error = 0.0_rp
   do spin = 1, 2
      do isite = 1, nsites
         site_ks_error(isite) = max(site_ks_error(isite), &
            maxval(abs(projector_ks(:, :, spin, isite)-projector_exact(:, :, spin, isite))))
      end do
      qlerr = max(qlerr,maxval(site_ks_error))
      if (qlerr > tol_ks) failed = .true.
   end do
   ! Deliberately compare the actual per-site production result against the
   ! other site's independent oracle.  Since the two sites have distinct
   ! local spectra and U/J, a site-index swap must be detectable.
   site_swap_mismatch = max(maxval(abs(projector_ks(:, :, :, 1)-projector_exact(:, :, :, 2))), &
                            maxval(abs(projector_ks(:, :, :, 2)-projector_exact(:, :, :, 1))))
   if (site_swap_mismatch < 1.0e-2_rp) failed = .true.
   ks_m1_site_swap_mismatch = max(maxval(abs(m1_ks(1,3,:,1:5,1:5)-m1_exact_ks(2,:,:,:))), &
                                    maxval(abs(m1_ks(2,3,:,1:5,1:5)-m1_exact_ks(1,:,:,:))))
   if (ks_m1_site_swap_mismatch < tol_wrong_m1) failed = .true.

   ! Negative control: conjugating every KS spinor reverses the imaginary
   ! projector coherences.  The production output must then disagree with the
   ! independent common-H projector by a large, measured margin.
   ks%eigenvectors = conjg(ks%eigenvectors)
   m1_wrong = cmplx(0.0_rp,0.0_rp,rp)
   call ks%calculate_ldm_from_projected_dos(lat, fixed_liechtenstein=.true., m1_out=m1_wrong)
   call copy_d_density(lat, 1, projector_wrong(:, :, :, 1))
   call copy_d_density(lat, 2, projector_wrong(:, :, :, 2))
   ks_conjugate_mismatch = maxval(abs(projector_wrong - projector_exact))
   if (ks_conjugate_mismatch < 0.1_rp) failed = .true.
   ks_m1_conjugate_mismatch = 0.0_rp
   do isite = 1, nsites
      ks_m1_conjugate_mismatch = max(ks_m1_conjugate_mismatch, &
         maxval(abs(m1_wrong(isite,3,:,1:5,1:5)-m1_exact_ks(isite,:,:,:))))
   end do
   if (ks_m1_conjugate_mismatch < tol_wrong_m1) failed = .true.
   ks%eigenvectors = conjg(ks%eigenvectors)

   call setup_rs_green(.true.)
   m1_rs = cmplx(0.0_rp,0.0_rp,rp)
   call rs%calculate_moments(m1_out=m1_rs)
   call copy_d_density(lat, 1, projector_rs(:, :, :, 1))
   call copy_d_density(lat, 2, projector_rs(:, :, :, 2))
   site_rs_error = 0.0_rp
   site_trace = 0.0_rp
   do isite = 1, nsites
      do spin = 1, 2
         site_rs_error(isite) = max(site_rs_error(isite), &
            maxval(abs(projector_rs(:, :, spin, isite)-projector_lorentz(:, :, spin, isite))))
         do a = 1, 5
            site_trace(isite,spin) = site_trace(isite,spin) + real(projector_rs(a,a,spin,isite),rp)
         end do
      end do
   end do
   rs_m1_site_swap_mismatch = max(maxval(abs(m1_rs(1,3,:,1:5,1:5)-m1_exact_rs(2,:,:,:))), &
                                    maxval(abs(m1_rs(2,3,:,1:5,1:5)-m1_exact_rs(1,:,:,:))))
   if (rs_m1_site_swap_mismatch < tol_wrong_m1) failed = .true.
   site_swap_mismatch = max(site_swap_mismatch, &
      max(maxval(abs(projector_rs(:, :, :, 1)-projector_lorentz(:, :, :, 2))), &
          maxval(abs(projector_rs(:, :, :, 2)-projector_lorentz(:, :, :, 1)))))
   if (site_swap_mismatch < 1.0e-2_rp) failed = .true.
   call run_simpson_mesh_refinement(refinement_errors, m1_refinement_errors, projector_simpson, m1_simpson)
   rs_quad_error = maxval(abs(projector_rs - projector_lorentz))
   rs_vs_simpson = maxval(abs(projector_rs - projector_simpson))
   broadening_error = maxval(abs(projector_lorentz - projector_exact))
   rs_m1_error = 0.0_rp
   rs_m1_vs_simpson = 0.0_rp
   rs_m1_trace_error = 0.0_rp
   do isite = 1, nsites
      rs_m1_error = max(rs_m1_error, maxval(abs(m1_rs(isite,3,:,1:5,1:5)-m1_exact_rs(isite,:,:,:))))
      rs_m1_vs_simpson = max(rs_m1_vs_simpson, maxval(abs(m1_rs(isite,3,:,1:5,1:5)-m1_simpson(isite,:,:,:))))
      do spin = 1, 2
         rs_m1_trace_error = max(rs_m1_trace_error, abs(real(sum([(m1_rs(isite,3,spin,a,a),a=1,5)]),rp) - &
            lat%symbolic_atoms(isite)%potential%ql(1,2,spin) * &
            (lat%symbolic_atoms(isite)%potential%gravity_center(3,spin) + lat%symbolic_atoms(isite)%potential%vmad)))
      end do
   end do
   if (rs_m1_error > tol_rs_m1 .or. rs_m1_vs_simpson > 5.0e-12_rp .or. &
       rs_m1_trace_error > tol_trace_m1) failed = .true.
   if (rs_quad_error > tol_rs_quad) failed = .true.
   if (rs_vs_simpson > 5.0e-12_rp) failed = .true.
   if (any(refinement_errors(2:4) >= refinement_errors(1:3))) failed = .true.
   if (refinement_errors(4) > tol_rs_quad) failed = .true.
   if (any(m1_refinement_errors(2:4) >= m1_refinement_errors(1:3))) failed = .true.
   if (m1_refinement_errors(4) > tol_rs_m1) failed = .true.
   if (broadening_error <= rs_quad_error) failed = .true.

   imag_coherence = maxval(abs(aimag(projector_exact)))
   v_imag = maxval(abs(aimag(ham%hubbard_u_pot)) )
   if (imag_coherence < 1.0e-2_rp .or. v_imag < 1.0e-5_rp) failed = .true.

   ! Negative control on the RS spectral matrix: H^T has P^T and flips the
   ! complex orbital coherences while leaving the spectrum unchanged.
   call setup_rs_green(.false.)
   m1_wrong = cmplx(0.0_rp,0.0_rp,rp)
   call rs%calculate_moments(m1_out=m1_wrong)
   call copy_d_density(lat, 1, projector_wrong(:, :, :, 1))
   call copy_d_density(lat, 2, projector_wrong(:, :, :, 2))
   rs_transpose_mismatch = maxval(abs(projector_wrong - projector_exact))
   if (rs_transpose_mismatch < 0.1_rp) failed = .true.
   rs_m1_transpose_mismatch = 0.0_rp
   do isite = 1, nsites
      rs_m1_transpose_mismatch = max(rs_m1_transpose_mismatch, &
         maxval(abs(m1_wrong(isite,3,:,1:5,1:5)-m1_exact_rs(isite,:,:,:))))
   end do
   if (rs_m1_transpose_mismatch < tol_wrong_m1) failed = .true.

   call test_rd1_recursive_vin_oracle()

#ifdef USE_MPI
   call reduce_failure(failed)
#endif
   if (rank == 0) then
      write(*,'(a,es14.6)') 'KS max error vs exact frozen-H projector = ', maxval(abs(projector_ks - projector_exact))
      do isite = 1, nsites
         write(*,'(a,i0,a,es14.6,a,es14.6,a,es14.6)') 'site=',isite,' KS error=',site_ks_error(isite), &
            ' RS Lorentz error=',site_rs_error(isite),' TrP(up+dn)=',sum(site_trace(isite,:))
      end do
      write(*,'(a,es14.6)') 'RS max quadrature error vs finite-window Lorentz oracle = ', rs_quad_error
      write(*,'(a,es14.6)') 'RS production vs 6000-point Simpson reference = ', rs_vs_simpson
      write(*,'(a,es14.6)') 'KS M1 max error vs exact eigenpair sum [Ry] = ', ks_m1_error
      write(*,'(a,es14.6)') 'RS M1 max error vs analytic finite-window Lorentz oracle [Ry] = ', rs_m1_error
      write(*,'(a,es14.6)') 'RS M1 production vs 6000-point Simpson reference [Ry] = ', rs_m1_vs_simpson
      write(*,'(a,es14.6)') 'KS max |Tr(M1)-q0*c| [Ry] = ', ks_m1_trace_error
      write(*,'(a,es14.6)') 'RS max |Tr(M1)-q0*c| [Ry] = ', rs_m1_trace_error
      do ik = 1, size(refinement_meshes)
         write(*,'(a,i0,a,es14.6)') 'Lorentz-oracle Simpson error nchannels=', refinement_meshes(ik), ' = ', refinement_errors(ik)
         write(*,'(a,i0,a,es14.6)') 'Lorentz M1 Simpson error nchannels=', refinement_meshes(ik), ' = ', &
            m1_refinement_errors(ik)
      end do
      write(*,'(a,es14.6)') 'RS broadening/window difference vs sharp KS projector = ', broadening_error
      write(*,'(a,es14.6)') 'max exact imaginary d coherence = ', imag_coherence
      write(*,'(a,es14.6)') 'max imaginary production V_U entry = ', v_imag
      write(*,'(a,es14.6)') 'max |(H0+V_U)-H| = ', h_identity_error
      write(*,'(a,es14.6)') 'max |H-H^dagger| = ', h_hermiticity_error
      write(*,'(a,es14.6)') 'KS conjugation negative-control mismatch = ', ks_conjugate_mismatch
      write(*,'(a,es14.6)') 'RS transpose negative-control mismatch = ', rs_transpose_mismatch
      write(*,'(a,es14.6)') 'KS M1 conjugation negative-control mismatch [Ry] = ', ks_m1_conjugate_mismatch
      write(*,'(a,es14.6)') 'RS M1 transpose negative-control mismatch [Ry] = ', rs_m1_transpose_mismatch
      write(*,'(a,es14.6)') 'KS M1 site-swap negative-control mismatch [Ry] = ', ks_m1_site_swap_mismatch
      write(*,'(a,es14.6)') 'RS M1 site-swap negative-control mismatch [Ry] = ', rs_m1_site_swap_mismatch
      write(*,'(a,es14.6)') 'deliberate site-swap negative-control mismatch = ', site_swap_mismatch
      if (failed) then
         write(*,'(a)') 'projector_multisite_frozen_h: FAIL'
      else
         write(*,'(a)') 'projector_multisite_frozen_h: PASS'
      end if
   end if
#ifdef USE_MPI
   call parallel%restore_to_default()
   call MPI_FINALIZE(ierr)
#endif
   if (failed) error stop 1

contains

   subroutine test_rd1_recursive_vin_oracle()
      integer :: nspinorb
      integer :: spin_id, i, j, site_i, site_j, orb_i, orb_j, row_i, row_j, state
      integer :: info, lwork, status, extract_status, drow(5)
      integer :: global_i, global_j, host_type, recursive_type, mapped_cluster, mapped_type
      integer :: surface_map_status, es_type, frozen_host_type
      complex(rp), allocatable :: spin_h(:,:), h_total(:,:), hbare(:,:)
      complex(rp) :: p_d(5,5), m1_d(5,5), vin_d(5,5), host_vin(5,5)
      complex(rp) :: captured(5,5,2), captured_valid(5,5,2), captured_probe(5,5,2), host_state_before(2,5,5)
      complex(rp) :: work_query(1)
      complex(rp), allocatable :: work(:), eigenvectors(:,:)
      real(rp), allocatable :: eigenvalues(:), rwork(:)
      real(rp) :: q0, center, q2, corrected_center, corrected_q2, t_value
      real(rp) :: direct_center, direct_q2, wrong_center, wrong_q2, host_center_before
      real(rp) :: oracle_error
      real(rp) :: saved_host_u, saved_host_j
      logical :: surface_es_has_uj
      integer :: saved_nrec, saved_nbulk, saved_ntype
      integer :: saved_nsp, saved_lmax
      integer, allocatable :: saved_irec(:), saved_ib(:), saved_iz(:)
      type(symbolic_atom), allocatable :: saved_surface_symbols(:)
      character :: saved_calctype
      character(len=16) :: saved_radial_mode, saved_potential_form
      character(len=16) :: saved_test_operator
      logical :: saved_constraints, saved_general, saved_impurity, saved_sc, saved_v, saved_test, saved_hoh, saved_hoh_bypass
      external :: zheev

      nspinorb = nsites*norb
      allocate(spin_h(nspinorb,nspinorb), h_total(nspinorb,nspinorb), hbare(nspinorb,nspinorb), &
               eigenvalues(nspinorb), rwork(max(1,3*nspinorb-2)))
      saved_nrec = lat%nrec
      saved_nbulk = lat%nbulk
      saved_ntype = lat%ntype
      saved_nsp = ctl%nsp
      saved_lmax = ctl%lmax
      saved_calctype = ctl%calctype
      saved_constraints = ctl%constraints_enable
      saved_radial_mode = ham%hubbard_radial_moments
      saved_potential_form = ham%hubbard_u_potential_form
      saved_general = ham%hubbard_u_general_check
      saved_impurity = ham%hubbard_u_impurity_check
      saved_sc = ham%hubbard_u_sc_check
      saved_v = ham%hubbard_v_check
      saved_test = ham%hubbard_test_operator_check
      saved_test_operator = ham%hubbard_test_operator
      saved_hoh = ham%hoh
      saved_hoh_bypass = ham%fixed_u_test_allow_hoh_w1_u0
      saved_ib = lat%ib
      saved_iz = lat%iz
      if (allocated(lat%irec)) saved_irec = lat%irec
      host_type = 1
      recursive_type = 2
      lat%nrec = 1
      lat%nbulk = 1
      if (allocated(lat%irec)) deallocate(lat%irec)
      allocate(lat%irec(1))
      lat%irec = [2]
      ! Deliberately leave ib(1)=1 while irec(1)=2 and iz(2)=2.
      lat%ib(1) = host_type
      lat%iz(1) = host_type
      lat%iz(2) = recursive_type
      ctl%calctype = 'I'
      ctl%nsp = 1
      ctl%lmax = 2
      ctl%constraints_enable = .false.
      ham%hubbard_radial_moments = 'local'
      ham%hubbard_u_potential_form = 'liechtenstein'
      ham%hubbard_u_general_check = .true.
      ham%hubbard_u_impurity_check = .false.
      ham%hubbard_u_sc_check = .false.
      ham%hubbard_v_check = .false.
      ham%hubbard_test_operator_check = .false.
      ham%fixed_u_test_allow_hoh_w1_u0 = .false.
      ham%hoh = .false.
      ham%hubbard_u_general_check = .false.
      ham%hubbard_u_impurity_check = .true.
      if (.not. ham%rd1_local_impurity_eligible()) failed = .true.
      ham%hubbard_u_general_check = .true.
      ham%hubbard_u_impurity_check = .false.
      ham%hubbard_test_operator = 'w1'
      ham%hubbard_test_operator_check = .true.
      if (ham%rd1_local_impurity_eligible()) failed = .true.
      call ham%get_rd1_recursion_site_type(1, mapped_cluster, mapped_type, status)
      if (status /= rd1_vin_ok .or. mapped_cluster /= 2 .or. mapped_type /= recursive_type) failed = .true.
      write(*,'(a,4(i0,1x))') 'RD1_CAPTURE map rec-index cluster type status=', 1, mapped_cluster, mapped_type, status
      ham%hubbard_test_operator = saved_test_operator
      ham%hubbard_test_operator_check = .false.
      ham%hubbard_u_general_check = .true.
      ham%hubbard_u_impurity_check = .true.

      do spin_id = 1, 2
         host_state_before(spin_id,:,:) = lat%symbolic_atoms(host_type)%potential%ldm(3, spin_id, 1:5, 1:5)
      end do
      host_center_before = lat%symbolic_atoms(host_type)%potential%gravity_center(3, 1)
      call ham%begin_rd1_vin_capture(7, enable_rs_capture=.true.)
      call ham%capture_rd1_vin_insertion(1, host_type, ham%hubbard_u_pot(:, :, host_type), status)
      if (status /= rd1_vin_not_recursion_site) failed = .true.
      call ham%capture_rd1_vin_insertion(2, host_type, ham%hubbard_u_pot(:, :, host_type), status)
      if (status /= rd1_vin_wrong_type) failed = .true.
      call ham%capture_rd1_vin_insertion(2, recursive_type, ham%hubbard_u_pot(:, :, recursive_type), status)
      if (status /= rd1_vin_ok) failed = .true.
      call ham%capture_rd1_vin_insertion(2, recursive_type, ham%hubbard_u_pot(:, :, recursive_type), status)
      if (status /= rd1_vin_duplicate) failed = .true.
      call ham%get_rd1_vin_for_recursion(1, 7, captured, status)
      if (status /= rd1_vin_ok) failed = .true.
      if (maxval(abs(captured(:, :, 1)-captured(:, :, 2))) <= 1.0e-5_rp) failed = .true.
      captured_valid = captured
      if (maxval(abs(captured_valid)) <= 1.0e-5_rp) failed = .true.
      do spin_id = 1, 2
         call extract_hubbard_d_shell_potential(ham%hubbard_u_pot, recursive_type, spin_id, &
            spin_off, vin_d, extract_status)
         if (extract_status /= 0 .or. maxval(abs(captured_valid(:, :, spin_id)-vin_d)) > 0.0_rp) failed = .true.
         call extract_hubbard_d_shell_potential(ham%hubbard_u_pot, host_type, spin_id, &
            spin_off, host_vin, extract_status)
         if (extract_status /= 0 .or. maxval(abs(captured_valid(:, :, spin_id)-host_vin)) <= 1.0e-5_rp) failed = .true.
      end do
      if (maxval(abs(host_state_before-lat%symbolic_atoms(host_type)%potential%ldm(3, :, 1:5, 1:5))) > 0.0_rp .or. &
          host_center_before /= lat%symbolic_atoms(host_type)%potential%gravity_center(3, 1)) failed = .true.
      call ham%get_rd1_vin_for_recursion(1, 6, captured_probe, status)
      if (status /= rd1_vin_missing_or_stale) failed = .true.

      drow = [(norb + 4 + i, i=1,5)]
      do spin_id = 1, 2
         do site_i = 1, nsites
            do orb_i = 1, norb
               i = (site_i-1)*norb + orb_i
               global_i = (site_i-1)*nb + (spin_id-1)*norb + orb_i
               do site_j = 1, nsites
                  do orb_j = 1, norb
                     j = (site_j-1)*norb + orb_j
                     global_j = (site_j-1)*nb + (spin_id-1)*norb + orb_j
                     spin_h(i,j) = htarget(global_i,global_j)
                  end do
               end do
            end do
         end do
         ! htarget is the finite two-site H with each type-specific V-in
         ! included once; the recursive d block is the captured operand.
         h_total = spin_h
         call zheev('V', 'U', nspinorb, spin_h, nspinorb, eigenvalues, work_query, -1, rwork, info)
         if (info /= 0) then
            failed = .true.
            cycle
         end if
         lwork = max(1, int(real(work_query(1), rp)))
         allocate(work(lwork), eigenvectors(nspinorb,nspinorb))
         call zheev('V', 'U', nspinorb, spin_h, nspinorb, eigenvalues, work, lwork, rwork, info)
         if (info /= 0) then
            failed = .true.
            deallocate(work, eigenvectors)
            cycle
         end if
         eigenvectors = spin_h
         p_d = cmplx(0.0_rp,0.0_rp,rp)
         m1_d = cmplx(0.0_rp,0.0_rp,rp)
         q2 = 0.0_rp
         direct_center = 0.0_rp
         direct_q2 = 0.0_rp
         do i = 1, 5
            row_i = drow(i)
            do j = 1, 5
               row_j = drow(j)
               do state = 1, nspinorb
                  if (eigenvalues(state) >= ef) cycle
                  p_d(i,j) = p_d(i,j) + eigenvectors(row_i,state)*conjg(eigenvectors(row_j,state))
                  m1_d(i,j) = m1_d(i,j) + eigenvalues(state)* &
                     eigenvectors(row_i,state)*conjg(eigenvectors(row_j,state))
               end do
            end do
         end do
         q0 = real(sum([(p_d(i,i),i=1,5)]),rp)
         center = real(sum([(m1_d(i,i),i=1,5)]),rp)/q0
         do state = 1, nspinorb
            if (eigenvalues(state) >= ef) cycle
            do i = 1, 5
               row_i = drow(i)
               q2 = q2 + abs(sum(h_total(row_i,:)*eigenvectors(:,state)) - &
                  center*eigenvectors(row_i,state))**2
            end do
         end do
         hbare = h_total
         do i = 1, 5
            do j = 1, 5
               row_i = drow(i)
               row_j = drow(j)
               hbare(row_i,row_j) = hbare(row_i,row_j) - captured_valid(i,j,spin_id)
            end do
         end do
         do state = 1, nspinorb
            if (eigenvalues(state) >= ef) cycle
            do i = 1, 5
               row_i = drow(i)
               direct_center = direct_center + real(conjg(eigenvectors(row_i,state))* &
                  sum(hbare(row_i,:)*eigenvectors(:,state)),rp)
            end do
         end do
         direct_center = direct_center/q0
         do state = 1, nspinorb
            if (eigenvalues(state) >= ef) cycle
            do i = 1, 5
               row_i = drow(i)
               direct_q2 = direct_q2 + abs(sum(hbare(row_i,:)*eigenvectors(:,state)) - &
                  direct_center*eigenvectors(row_i,state))**2
            end do
         end do
         call correct_d_shell_moments(p_d, m1_d, captured_valid(:, :, spin_id), q0, center, q2, &
            corrected_center, corrected_q2, t_value, status)
         if (status /= 0) failed = .true.
         oracle_error = max(abs(corrected_center-direct_center), abs(corrected_q2-direct_q2))
         if (oracle_error > 1.0e-12_rp) failed = .true.
         write(*,'(a,i0,1x,6(es24.16e3,1x))') &
            'RD1_ORACLE spin production_center production_q2 direct_center direct_q2 abs_center_error abs_q2_error=', &
            spin_id, corrected_center, corrected_q2, direct_center, direct_q2, &
            abs(corrected_center-direct_center), abs(corrected_q2-direct_q2)

         call extract_hubbard_d_shell_potential(ham%hubbard_u_pot, host_type, spin_id, &
            spin_off, host_vin, extract_status)
         if (extract_status /= 0) then
            failed = .true.
         else
            call correct_d_shell_moments(p_d, m1_d, host_vin, q0, center, q2, &
               wrong_center, wrong_q2, t_value, status)
            if (status /= 0 .or. max(abs(wrong_center-direct_center),abs(wrong_q2-direct_q2)) <= 1.0e-12_rp) then
               failed = .true.
            end if
         end if
         write(*,'(a,2(i0,1x),4(es24.16e3,1x))') &
            'RD1_ORACLE wrong_site spin status wrong_center wrong_q2 abs_center_error abs_q2_error=', &
            spin_id, status, wrong_center, wrong_q2, abs(wrong_center-direct_center), abs(wrong_q2-direct_q2)
         deallocate(work, eigenvectors)
      end do

      ! Surface-like map with three distinct roles: the frozen host is type 1
      ! (selected by ib), the U recursion site is type 2, and the ES recursion
      ! site is type 3 with no U/J. Only the latter two are in irec.
      frozen_host_type = host_type
      es_type = 3
      saved_host_u = lat%symbolic_atoms(frozen_host_type)%potential%hubbard_u(3)
      saved_host_j = lat%symbolic_atoms(frozen_host_type)%potential%hubbard_j(3)
      if (saved_host_u <= 0.0_rp .or. saved_host_j <= 0.0_rp) failed = .true.
      call move_alloc(lat%symbolic_atoms, saved_surface_symbols)
      allocate(lat%symbolic_atoms(3))
      lat%symbolic_atoms(1:2) = saved_surface_symbols
      call lat%symbolic_atoms(es_type)%restore_to_default()
      deallocate(lat%iz)
      allocate(lat%iz(3))
      lat%iz = [frozen_host_type, es_type, recursive_type]
      lat%ntype = 3
      lat%ib(1) = frozen_host_type
      if (allocated(lat%irec)) deallocate(lat%irec)
      allocate(lat%irec(2))
      lat%irec = [2, 3]
      lat%nrec = 2
      ctl%calctype = 'S'
      ham%hubbard_u_general_check = .true.
      ham%hubbard_u_impurity_check = .false.
      if (.not. ham%rd1_local_impurity_eligible()) failed = .true.
      if (lat%ib(1) /= frozen_host_type .or. &
          lat%symbolic_atoms(frozen_host_type)%potential%hubbard_u(3) <= 0.0_rp .or. &
          lat%symbolic_atoms(frozen_host_type)%potential%hubbard_j(3) <= 0.0_rp) failed = .true.
      call ham%get_rd1_recursion_site_type(1, mapped_cluster, mapped_type, surface_map_status)
      if (surface_map_status /= rd1_vin_ok .or. mapped_cluster /= 2 .or. mapped_type /= es_type) failed = .true.
      surface_es_has_uj = .false.
      if (allocated(lat%symbolic_atoms(es_type)%potential%hubbard_u)) then
         surface_es_has_uj = any(abs(lat%symbolic_atoms(es_type)%potential%hubbard_u) > 1.0e-10_rp)
      end if
      if (allocated(lat%symbolic_atoms(es_type)%potential%hubbard_j)) then
         surface_es_has_uj = surface_es_has_uj .or. &
            any(abs(lat%symbolic_atoms(es_type)%potential%hubbard_j) > 1.0e-10_rp)
      end if
      if (surface_es_has_uj) failed = .true.
      call ham%get_rd1_recursion_site_type(2, mapped_cluster, mapped_type, surface_map_status)
      if (surface_map_status /= rd1_vin_ok .or. mapped_cluster /= 3 .or. mapped_type /= recursive_type) failed = .true.
      if (lat%symbolic_atoms(mapped_type)%potential%hubbard_u(3) <= 0.0_rp .or. &
          lat%symbolic_atoms(mapped_type)%potential%hubbard_j(3) <= 0.0_rp) failed = .true.
      call extract_hubbard_d_shell_potential(ham%hubbard_u_pot, mapped_type, 2, spin_off, vin_d, extract_status)
      if (extract_status /= 0) failed = .true.
      call correct_d_shell_moments(p_d, m1_d, vin_d, q0, center, q2, &
         corrected_center, corrected_q2, t_value, status)
      if (status /= 0 .or. max(abs(corrected_center-direct_center), abs(corrected_q2-direct_q2)) > 1.0e-12_rp) then
         failed = .true.
      end if
      write(*,'(a,6(i0,1x),es24.16e3)') &
         'RD1_SURFACE frozen_host ES_cluster ES_type U_cluster U_type ES_has_UJ moment_error=', &
         frozen_host_type, 2, es_type, 3, mapped_type, merge(1, 0, surface_es_has_uj), &
         max(abs(corrected_center-direct_center), abs(corrected_q2-direct_q2))
      call ham%begin_rd1_vin_capture(9, enable_rs_capture=.true.)
      if (.not. ham%rd1_capture_required .or. .not. ham%rd1_capture_enabled) failed = .true.
      call ham%capture_rd1_vin_insertion(3, recursive_type, ham%hubbard_u_pot(:, :, recursive_type), status)
      if (status /= rd1_vin_ok) failed = .true.
      call ham%get_rd1_vin_for_recursion(1, 9, captured_probe, status)
      if (status /= rd1_vin_missing_or_stale) failed = .true.
      call ham%get_rd1_vin_for_recursion(2, 9, captured_probe, status)
      if (status /= rd1_vin_ok .or. maxval(abs(captured_probe(:, :, 2)-vin_d)) > 0.0_rp) failed = .true.
      deallocate(lat%symbolic_atoms)
      call move_alloc(saved_surface_symbols, lat%symbolic_atoms)

      call ham%begin_rd1_vin_capture(8, enable_rs_capture=.true.)
      call ham%get_rd1_vin_for_recursion(1, 8, captured_probe, status)
      if (status /= rd1_vin_missing_or_stale) failed = .true.
      call ham%begin_rd1_vin_capture(0, enable_rs_capture=.true.)
      if (.not. ham%rd1_capture_required .or. ham%rd1_capture_enabled) failed = .true.
      call ham%get_rd1_vin_for_recursion(1, 7, captured_probe, status)
      if (status /= rd1_vin_missing_or_stale) failed = .true.
      call ham%begin_rd1_vin_capture(0, enable_rs_capture=.false.)
      if (allocated(lat%irec)) deallocate(lat%irec)
      if (allocated(saved_irec)) then
         allocate(lat%irec(size(saved_irec)))
         lat%irec = saved_irec
      end if
      lat%ib = saved_ib
      lat%iz = saved_iz
      lat%nrec = saved_nrec
      lat%nbulk = saved_nbulk
      lat%ntype = saved_ntype
      ctl%nsp = saved_nsp
      ctl%lmax = saved_lmax
      ctl%calctype = saved_calctype
      ctl%constraints_enable = saved_constraints
      ham%hubbard_radial_moments = saved_radial_mode
      ham%hubbard_u_potential_form = saved_potential_form
      ham%hubbard_u_general_check = saved_general
      ham%hubbard_u_impurity_check = saved_impurity
      ham%hubbard_u_sc_check = saved_sc
      ham%hubbard_v_check = saved_v
      ham%hubbard_test_operator_check = saved_test
      ham%hubbard_test_operator = saved_test_operator
      ham%hoh = saved_hoh
      ham%fixed_u_test_allow_hoh_w1_u0 = saved_hoh_bypass
      deallocate(spin_h, h_total, hbare, eigenvalues, rwork)
   end subroutine test_rd1_recursive_vin_oracle

   subroutine run_simpson_mesh_refinement(errors, m1_errors, finest_projector, finest_m1)
      real(rp), intent(out) :: errors(4)
      real(rp), intent(out) :: m1_errors(4)
      complex(rp), intent(out) :: finest_projector(5,5,2,nsites)
      complex(rp), intent(out) :: finest_m1(nsites,2,5,5)
      real(rp), allocatable :: energy_mesh(:), y_real(:), y_imag(:)
      complex(rp) :: spectral, g_ab, g_ba
      complex(rp) :: integrated(5,5,2,nsites), integrated_m1(5,5,2,nsites)
      complex(rp) :: expected_m1(5,5,2,nsites)
      real(rp) :: step, endpoint, egrid, value_real, value_imag, m1_value_real, m1_value_imag
      integer :: level, nchan, npts, iorb_a, iorb_b, spin_id, spin_offset, row, col, band_id, ie, isite

      finest_projector = cmplx(0.0_rp,0.0_rp,rp)
      finest_m1 = cmplx(0.0_rp,0.0_rp,rp)
      do isite = 1, nsites
         do spin_id = 1, 2
            expected_m1(:,:,spin_id,isite) = m1_exact_rs(isite,spin_id,:,:)
         end do
      end do
      do level = 1, size(refinement_meshes)
         nchan = refinement_meshes(level)
         step = (ef-emin)/real(nchan/2,rp)
         npts = nint((ef-emin)/step)
         endpoint = emin + real(npts-1,rp)*step
         allocate(energy_mesh(nchan+10), y_real(nchan+10), y_imag(nchan+10))
         do ie = 1, nchan+10
            energy_mesh(ie) = emin + real(ie-1,rp)*step
         end do
         integrated = cmplx(0.0_rp,0.0_rp,rp)
         integrated_m1 = cmplx(0.0_rp,0.0_rp,rp)
         do isite = 1, nsites
            do spin_id = 1, 2
               spin_offset = (isite-1)*nb + (spin_id-1)*norb
               do iorb_a = 1, 5
                  row = spin_offset + 4 + iorb_a
                  do iorb_b = 1, 5
                     col = spin_offset + 4 + iorb_b
                     do ie = 1, nchan+10
                        egrid = energy_mesh(ie)
                        spectral = cmplx(0.0_rp,0.0_rp,rp)
                        do band_id = 1, nsites*nb
                           g_ab = q(row,band_id)*conjg(q(col,band_id))/ &
                                  cmplx(egrid-eig(band_id),eta,rp)
                           g_ba = q(col,band_id)*conjg(q(row,band_id))/ &
                                  cmplx(egrid-eig(band_id),eta,rp)
                           spectral = spectral + hubbard_spectral_density_element(g_ab,g_ba)
                        end do
                        y_real(ie) = real(spectral,rp)
                        y_imag(ie) = aimag(spectral)
                     end do
                     call simpson_m(value_real,step,ef,npts,y_real,endpoint,0,energy_mesh)
                     call simpson_m(value_imag,step,ef,npts,y_imag,endpoint,0,energy_mesh)
                     integrated(iorb_a,iorb_b,spin_id,isite) = cmplx(value_real,value_imag,rp)
                     do ie = 1, nchan+10
                        egrid = energy_mesh(ie)
                        spectral = cmplx(0.0_rp,0.0_rp,rp)
                        do band_id = 1, nsites*nb
                           g_ab = q(row,band_id)*conjg(q(col,band_id))/ &
                                  cmplx(egrid-eig(band_id),eta,rp)
                           g_ba = q(col,band_id)*conjg(q(row,band_id))/ &
                                  cmplx(egrid-eig(band_id),eta,rp)
                           spectral = spectral + hubbard_spectral_density_element(g_ab,g_ba)
                        end do
                        y_real(ie) = egrid*real(spectral,rp)
                        y_imag(ie) = egrid*aimag(spectral)
                     end do
                     call simpson_m(m1_value_real,step,ef,npts,y_real,endpoint,0,energy_mesh)
                     call simpson_m(m1_value_imag,step,ef,npts,y_imag,endpoint,0,energy_mesh)
                     integrated_m1(iorb_a,iorb_b,spin_id,isite) = cmplx(m1_value_real,m1_value_imag,rp)
                  end do
               end do
            end do
         end do
         errors(level) = maxval(abs(integrated-projector_lorentz))
         m1_errors(level) = maxval(abs(integrated_m1-expected_m1))
         if (level == size(refinement_meshes)) finest_projector = integrated
         if (level == size(refinement_meshes)) then
            do isite = 1, nsites
               do spin_id = 1, 2
                  finest_m1(isite,spin_id,:,:) = integrated_m1(:,:,spin_id,isite)
               end do
            end do
         end if
         deallocate(energy_mesh,y_real,y_imag)
      end do
   end subroutine run_simpson_mesh_refinement


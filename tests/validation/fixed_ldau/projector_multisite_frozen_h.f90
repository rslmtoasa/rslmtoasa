      rs%e1 = en%energy_min + real(rs%nv1-1,rp)*en%edel
   end subroutine setup_objects

   subroutine setup_common_operator()
      integer :: i, j, k, isite, local_i, local_j, spin_offset, row, col, m, id
      integer :: dindex(10), global_index(2*norb), site_index
      complex(rp) :: phase, base_q(5,5), base10(10,10), rotation(10,10), qd(10,10)
      complex(rp) :: dmat(nsites*nb,nsites*nb), vsite(nb,nb)
      real(rp) :: occ, occ_m1, theta

      ! Two different Hermitian seed occupations and U/J make the local
      ! potentials/site blocks inequivalent; both have complex d coherence.
      do isite = 1, nsites
         do spin = 1, 2
            do i = 1, 5
               lat%symbolic_atoms(isite)%potential%ldm(3,spin,i,i) = &
                  (0.13_rp + 0.055_rp*real(i,rp) + 0.025_rp*real(isite-1,rp) + 0.018_rp*real(spin-1,rp))
               do j = i+1, 5
                  phase = cmplx(0.007_rp*real(i+j+isite,rp), 0.003_rp*real(i-j+spin,rp), rp)
                  lat%symbolic_atoms(isite)%potential%ldm(3,spin,i,j) = phase
                  lat%symbolic_atoms(isite)%potential%ldm(3,spin,j,i) = conjg(phase)
               end do
            end do
         end do
      end do
      call ham%calculate_hubbard_u_potential_general()

      ! Per-spin 18x18 unitary: s/p stay local; complex Fourier mixing within
      ! each d shell is followed by distinct site-mixing rotations. This gives
      ! noncubic complex blocks and a measurable site-index negative control.
      base_q = cmplx(0.0_rp,0.0_rp,rp)
      do i = 1, 5
         do j = 1, 5
            angle = 2.0_rp*pi*real((i-1)*(j-1),rp)/5.0_rp
            base_q(i,j) = cmplx(cos(angle),sin(angle),rp)/sqrt(5.0_rp)
         end do
      end do
      base10 = cmplx(0.0_rp,0.0_rp,rp)
      base10(1:5,1:5) = base_q
      base10(6:10,6:10) = base_q
      rotation = cmplx(0.0_rp,0.0_rp,rp)
      do i = 1, 10
         rotation(i,i) = cmplx(1.0_rp,0.0_rp,rp)
      end do
      do m = 1, 5
         theta = 0.13_rp + 0.075_rp*real(m,rp)
         phase = cmplx(cos(0.31_rp*real(m,rp)),sin(0.31_rp*real(m,rp)),rp)
         rotation(m,m) = cmplx(cos(theta),0.0_rp,rp)
         rotation(m,m+5) = phase*sin(theta)
         rotation(m+5,m) = -conjg(phase)*sin(theta)
         rotation(m+5,m+5) = cmplx(cos(theta),0.0_rp,rp)
      end do
      qd = matmul(rotation,base10)
      dindex = [5,6,7,8,9,14,15,16,17,18]
      q = cmplx(0.0_rp,0.0_rp,rp)
      eig = 0.0_rp
      do spin = 1, 2
         spin_offset = (spin-1)*norb
         do isite = 1, nsites
            do local_i = 1, norb
               id = (isite-1)*nb + spin_offset + local_i
               global_index((isite-1)*norb+local_i) = id
               q(id,id) = cmplx(1.0_rp,0.0_rp,rp)
            end do
         end do
         do i = 1, 10
            do j = 1, 10
               row = global_index(dindex(i))
               col = global_index(dindex(j))
               q(row,col) = qd(i,j)
            end do
         end do
         eig(global_index(1:4)) = [-1.40_rp,-1.00_rp,-0.80_rp,-0.60_rp] + 0.03_rp*real(spin-1,rp)
         eig(global_index(10:13)) = [-1.31_rp,-0.91_rp,-0.71_rp,-0.51_rp] + 0.03_rp*real(spin-1,rp)
         eig(global_index(dindex(1:5))) = [-0.34_rp,-0.19_rp,0.16_rp,0.39_rp,0.61_rp] + 0.03_rp*real(spin-1,rp)
         ! The second site's second d level is above EF while the first site's
         ! partner remains occupied, so site mixing produces distinct local P.
         eig(global_index(dindex(6:10))) = [-0.27_rp,0.14_rp,0.23_rp,0.46_rp,0.72_rp] + 0.03_rp*real(spin-1,rp)
      end do
      dmat = cmplx(0.0_rp,0.0_rp,rp)
      do i = 1, nsites*nb
         dmat(i,i) = cmplx(eig(i),0.0_rp,rp)
      end do
      htarget = matmul(q,matmul(dmat,transpose(conjg(q))))
      vglobal = cmplx(0.0_rp,0.0_rp,rp)
      do isite = 1, nsites
         id = (isite-1)*nb
         vsite = ham%hubbard_u_pot(:,:,isite)
         vglobal(id+1:id+nb,id+1:id+nb) = vsite
      end do
      hbare = htarget-vglobal
      hcheck = hbare+vglobal
      h_identity_error = maxval(abs(hcheck-htarget))
      h_hermiticity_error = maxval(abs(htarget-transpose(conjg(htarget))))
      if (h_identity_error > 2.0e-14_rp .or. h_hermiticity_error > 2.0e-14_rp) failed = .true.

      projector_exact = cmplx(0.0_rp,0.0_rp,rp)
      projector_lorentz = cmplx(0.0_rp,0.0_rp,rp)
      m1_exact_ks = cmplx(0.0_rp,0.0_rp,rp)
      m1_exact_rs = cmplx(0.0_rp,0.0_rp,rp)
      do isite = 1, nsites
         do spin = 1, 2
            do a = 1, 5
               row = (isite-1)*nb + (spin-1)*norb + 4 + a
               do b = 1, 5
                  col = (isite-1)*nb + (spin-1)*norb + 4 + b
                  do k = 1, nsites*nb
                     if (eig(k) < ef) then
                        projector_exact(a,b,spin,isite) = projector_exact(a,b,spin,isite)+q(row,k)*conjg(q(col,k))
                        m1_exact_ks(isite,spin,a,b) = m1_exact_ks(isite,spin,a,b)+ &
                           eig(k)*q(row,k)*conjg(q(col,k))
                     end if
                     occ = (atan((ef-eig(k))/eta)-atan((emin-eig(k))/eta))/pi
                     occ_m1 = eig(k)*occ + eta/(2.0_rp*pi)*log(((ef-eig(k))**2+eta**2)/ &
                                                                ((emin-eig(k))**2+eta**2))
                     projector_lorentz(a,b,spin,isite) = projector_lorentz(a,b,spin,isite)+ &
                        occ*q(row,k)*conjg(q(col,k))
                     m1_exact_rs(isite,spin,a,b) = m1_exact_rs(isite,spin,a,b)+ &
                        occ_m1*q(row,k)*conjg(q(col,k))
                  end do
               end do
            end do
         end do
      end do
   end subroutine setup_common_operator

   subroutine setup_ks()
      real(rp) :: all_points(3,nk)
      type(kpoint_workset) :: workset

      all_points = 0.0_rp
      weights = 1.0_rp/real(nk,rp)
      workset = make_kpoint_workset(all_points,weights,parallel,numprocs>1,.true.)
      local_nk = workset%nk_local
      ks%hamiltonian => ham; ks%lattice => lat; ks%control => ctl
      ks%n_sites = nsites
      ks%n_orb_types = 3
      ks%n_spin_components = 2
      ks%nk_mesh = [nk, 1, 1]
      ks%nk_total = nk; ks%nk_local = local_nk
      ks%k_mesh_distributed_active = numprocs > 1
      ks%use_symmetry_reduction = .false.
      ks%temperature = 0.0_rp; ks%fermi_level = ef
      ks%k_workset = workset
      allocate(ks%eigenvalues(nsites*nb,local_nk),ks%eigenvectors(nsites*nb,nsites*nb,local_nk))
      allocate(ks%k_weights(nk),ks%k_l2g_map(local_nk),ks%k_g2l_map(nk))
      ks%k_weights = weights
      ks%k_points = all_points
      ks%k_l2g_map = workset%local_to_global
      ks%k_g2l_map = workset%global_to_local
      ks%cached_operator_generation = ham%operator_generation
      do ik = 1, local_nk
         ks%eigenvalues(:,ik) = eig
         ks%eigenvectors(:,:,ik) = q
      end do
   end subroutine setup_ks

   subroutine setup_rs_green(correct)
      logical, intent(in) :: correct
      integer :: local_atom, global_atom, site
      complex(rp) :: z

      if (allocated(gr%g0)) deallocate(gr%g0)
      allocate(gr%g0(nb,nb,nch+10,atoms_per_process))
      gr%g0 = cmplx(0.0_rp,0.0_rp,rp)
      if (start_atom > end_atom) return
      global_atom = start_atom
      local_atom = g2l_map(global_atom)
      if (allocated(gmat)) deallocate(gmat)
      allocate(gmat(nsites*nb,nsites*nb))
      do site = start_atom, end_atom
         local_atom = g2l_map(site)
         do ie = 1, nch+10
            e = en%ene(ie)
            gmat = cmplx(0.0_rp,0.0_rp,rp)
            do band = 1, nsites*nb
               z = cmplx(e-eig(band),eta,rp)
               do a = 1, nsites*nb
                  do b = 1, nsites*nb
                     if (correct) then
                        gmat(a,b) = gmat(a,b) + q(a,band)*conjg(q(b,band))/z
                     else
                        gmat(a,b) = gmat(a,b) + conjg(q(a,band))*q(b,band)/z
                     end if
                  end do
               end do
            end do
            do a = 1, nb
               do b = 1, nb
                  gr%g0(a,b,ie,local_atom) = gmat((site-1)*nb+a,(site-1)*nb+b)
               end do
            end do
         end do
      end do
   end subroutine setup_rs_green

   subroutine copy_d_density(lattice_obj, isite, output)
      type(lattice), intent(in) :: lattice_obj
      integer, intent(in) :: isite
      complex(rp), intent(out) :: output(5,5,2)
      integer :: s
      do s = 1, 2
         output(:,:,s) = lattice_obj%symbolic_atoms(isite)%potential%ldm(3,s,1:5,1:5)
      end do
   end subroutine copy_d_density


#!/usr/bin/env python3
"""Analytic and semi-analytic references A1-A3 for the spin_response C0 kernels.

Developer-owned oracle: generated by this script, reviewed by the developer,
committed under tests/spin_response/oracles/, read-only to AI sessions.

Conventions (spec, section "Conventions"):
  sigma+ = |up><dn|, no factor 2; Kubo sign; energies, omega, eta, U in Ry.
  chi0_ij(q,w) = sum_k w_k sum_{n,m} (f_nk - f_m,k+q) T_i T_j^* / (w + e_nk - e_m,k+q + i eta)
  T_i^{nm}     = sum_{mu in d} conj(a^{nk}_{i mu up}) a^{m,k+q}_{i mu dn}
  (I + chi0 U) chi = chi0,  U > 0 diagonal in sites,  Goldstone chi0(0,0) U M = -M
  L = -(chi - chi^H)/(2 pi i); one site: -Im chi / pi.

What each model anchors:
  A1  two-level, closed form.  Exact pole at delta*Delta; Mills variant.
  A2  self-consistent single band (5 degenerate orbitals, site U coupling the
      total moment), partially polarized (86%), so both spin bands are
      occupied at both endpoints.  Exact anchor: chi0(0,0) = -1/U at eta -> 0
      for any mesh and temperature.  Finite-q values are an independent
      evaluation of the spec formula (numpy, vectorized), not an analytic
      result.  Its magnons are very soft (about 4e-7 Ry at the smallest q), so
      magnon_eta0 is informational only; pole finding (C6) is tested by A1.
  A3  A2 on a doubled cell.  Exact anchor: the gauge-invariant cell response
      equals A2 at Q and Q + G_super.  Band phases are randomized, so the
      kernels must be phase-invariant to pass.

Output: one Fortran namelist file per model.  Complex arrays are written as
separate _re and _im arrays, in Fortran (column-major) order; each file states
its array dimensions and amplitude rule in string keys.  Only numpy is needed.

Suggested tolerances (the developer sets the final ones):
  A1 arrays and scalars          1e-12 relative (closed form)
  A2 chi0, chi arrays            1e-10 relative (different summation order)
  A2 Goldstone, zeroth moment    1e-12 relative (exact identities)
  A3 trace, determinant          1e-10 relative (self-check reaches ~1e-14)

Usage: python3 make_references.py [outdir]
"""
import sys
from pathlib import Path

import numpy as np

NORB = 5            # degenerate d copies for A1 and A2
NORB_A3 = 1         # orbital count for A3 (kernels must take it from the array shape)
ETA = 1.0e-3        # broadening for the finite-eta outputs (Ry)
ETA_STATIC = (4.0e-3, 2.0e-3, 1.0e-3, 5.0e-4)


# ----------------------------------------------------------------------------
# helpers
# ----------------------------------------------------------------------------
def fermi(e, ef, kt):
    """Fermi-Dirac occupation, stable form."""
    return 0.5 * (1.0 - np.tanh(0.5 * (e - ef) / kt))


def lehmann_pairs(w, de, weight, omega, eta):
    """sum_p weight_p * w_p / (omega + de_p + i eta), de_p = e_n - e_m.

    w, de, weight: arrays over pairs; omega: 1-D grid.  Returns complex array.
    """
    num = (w * weight)[None, :]
    den = omega[:, None] + de[None, :] + 1j * eta
    return (num / den).sum(axis=1)


def lehmann_static_eta0(w, f_n, f_m, e_n, e_m, kt, weight):
    """Same sum at omega = 0, eta = 0, with Fermi divided differences."""
    de = e_n - e_m
    out = np.empty_like(de)
    big = np.abs(de) > 1.0e-10
    out[big] = (f_n[big] - f_m[big]) / de[big]
    # (f_n - f_m)/(e_n - e_m) -> f'(e) = -f(1-f)/kT for degenerate pairs
    fe = f_n[~big]
    out[~big] = -fe * (1.0 - fe) / kt
    return float((w * weight * out).sum())


def window_moment(w, de, weight, eta, wa, wb):
    """Exact integral over [wa, wb] of -Im(sum)/pi for the finite-eta sum.

    Each pair is a Lorentzian at omega_p = -de_p with weight w*weight.
    """
    om = -de
    return float((w * weight * (np.arctan((wb - om) / eta)
                                - np.arctan((wa - om) / eta))).sum() / np.pi)


def bisect(fun, a, b, tol=1.0e-15, itmax=300):
    fa = fun(a)
    for _ in range(itmax):
        c = 0.5 * (a + b)
        fc = fun(c)
        if (fc > 0) == (fa > 0):
            a, fa = c, fc
        else:
            b = c
        if b - a < tol:
            break
    return 0.5 * (a + b)


def nml_value(v):
    if isinstance(v, (bool, np.bool_)):
        return ".true." if v else ".false."
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, str):
        return "'" + v + "'"
    return f"{float(v):.17e}"


def write_group(fh, name, items):
    fh.write(f"&{name}\n")
    for key, val in items:
        arr = np.asarray(val)
        if arr.ndim == 0:
            fh.write(f"  {key} = {nml_value(val)}\n")
        else:
            flat = arr.ravel(order="F")
            fh.write(f"  {key} =\n")
            for i in range(0, flat.size, 4):
                fh.write("    " + ", ".join(nml_value(x) for x in flat[i:i + 4]) + ",\n")
    fh.write("/\n\n")


def check(label, value, tol):
    status = "ok" if abs(value) <= tol else "FAIL"
    print(f"  [{status}] {label}: {value:.3e} (tol {tol:.0e})")
    if status == "FAIL":
        raise SystemExit(f"self-check failed: {label}")


# ----------------------------------------------------------------------------
# A1: two-level, closed form
# ----------------------------------------------------------------------------
def model_a1(outdir):
    print("A1 two-level")
    delta = 0.15                      # level splitting e_dn - e_up (Ry)
    dfrac = 0.0612                    # Goldstone residual; pole lies 0.36 grid steps off-grid
    mills_factor = 0.9                # band-centre splitting / level splitting (variant)
    m = float(NORB)                   # moment: NORB occupied up levels, empty down
    omega = np.linspace(-0.05, 0.25, 601)

    u_gold = delta / m
    u_test = (1.0 - dfrac) * delta / m
    chi0 = NORB / (omega - delta + 1j * ETA)
    chi = chi0 / (1.0 + chi0 * u_test)
    pole = dfrac * delta
    chi_closed = NORB / (omega - pole + 1j * ETA)
    check("chi from Dyson vs closed form 5/(w - d*Delta + i eta)",
          np.max(np.abs(chi - chi_closed)) / np.max(np.abs(chi_closed)), 1e-13)

    u_mills_var = mills_factor * delta / m
    resid_mills_var = 1.0 - (NORB / delta) * u_mills_var      # eta -> 0
    static_ladder = NORB / (-delta + 1j * np.array(ETA_STATIC))

    with open(outdir / "a1_two_level.nml", "w") as fh:
        write_group(fh, "a1_inputs", [
            ("norb", NORB), ("delta", delta), ("eta", ETA),
            ("amplitude_rule", "bands are (mu, spin); band (mu,s) has a = 1 at (mu, s), else 0"),
            ("e_up", 0.0), ("e_dn", delta), ("f_up", 1.0), ("f_dn", 0.0),
            ("u_test", u_test), ("mills_factor", mills_factor),
            ("nomega", omega.size), ("omega", omega),
            ("neta_static", len(ETA_STATIC)), ("eta_static", np.array(ETA_STATIC)),
        ])
        write_group(fh, "a1_expected", [
            ("moment", m), ("u_goldstone", u_gold),
            ("chi0_static_eta0", -NORB / delta),
            ("chi0_static_ladder_re", static_ladder.real),
            ("chi0_static_ladder_im", static_ladder.imag),
            ("pole", pole), ("pole_weight", float(NORB)),
            ("u_mills_variant", u_mills_var),
            ("residual_mills_variant", resid_mills_var),
            ("gap_mills_variant", resid_mills_var * delta),
            ("chi0_re", chi0.real), ("chi0_im", chi0.imag),
            ("chi_re", chi.real), ("chi_im", chi.imag),
            ("spectral", -chi.imag / np.pi),
        ])
    print(f"  pole {pole:.6f} Ry, Mills-variant residual {resid_mills_var:.6f}")



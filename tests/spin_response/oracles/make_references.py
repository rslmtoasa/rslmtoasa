# A2: self-consistent single band, 1-D chain, NORB degenerate copies
# ----------------------------------------------------------------------------
def a2_ground_state(nk, t, filling, u, kt):
    k = 2.0 * np.pi * np.arange(nk) / nk          # lattice constant 1
    w = np.full(nk, 1.0 / nk)
    eps = -2.0 * t * np.cos(k)
    target = filling * NORB                        # electrons per site
    m = target                                     # start saturated
    for _ in range(2000):
        dlt = u * m                                # splitting e_dn - e_up
        eu, ed = eps - 0.5 * dlt, eps + 0.5 * dlt
        def nerr(ef):
            return NORB * (w * (fermi(eu, ef, kt) + fermi(ed, ef, kt))).sum() - target
        ef = bisect(nerr, eps.min() - dlt - 1.0, eps.max() + dlt + 1.0)
        m_new = NORB * (w * (fermi(eu, ef, kt) - fermi(ed, ef, kt))).sum()
        if abs(m_new - m) < 1e-15:
            m = m_new
            break
        m = 0.5 * m + 0.5 * m_new
    dlt = u * m
    eu, ed = eps - 0.5 * dlt, eps + 0.5 * dlt
    return dict(k=k, w=w, eps=eps, ef=ef, m=m, dlt=dlt, eu=eu, ed=ed,
                fu=fermi(eu, ef, kt), fd=fermi(ed, ef, kt))


def a2_chi0(gs, q, t, omega, eta, kt):
    """chi0(q, omega) per site; transitions up(k) -> dn(k+q), NORB copies."""
    kq = gs["k"] + q
    edq = -2.0 * t * np.cos(kq) + 0.5 * gs["dlt"]
    fdq = fermi(edq, gs["ef"], kt)
    weight = NORB * (gs["fu"] - fdq)
    de = gs["eu"] - edq
    chi0 = lehmann_pairs(gs["w"], de, weight, omega, eta)
    static0 = lehmann_static_eta0(gs["w"], gs["fu"], fdq, gs["eu"], edq, kt,
                                  np.full_like(weight, float(NORB)))
    return chi0, static0, edq, fdq, de, weight


def a2_magnon(gs, q, t, u, kt):
    """Root of 1 + U chi0(q, omega) on the real axis at eta = 0, below the continuum."""
    _, _, edq, fdq, de, weight = a2_chi0(gs, q, t, np.array([0.0]), 0.0, kt)
    wcont = float((-de).min())                     # lowest transition energy
    def g(om):
        return 1.0 + u * float((gs["w"] * weight / (om + de)).sum())
    if g(0.0) <= 0.0:
        return float("nan"), wcont                 # unstable at this q
    hi = wcont * (1.0 - 1e-12)
    if g(hi) > 0.0:
        return float("nan"), wcont                 # no root below the continuum
    return bisect(g, 0.0, hi), wcont


def model_a2(outdir, nk=400, t=0.05, filling=0.15, u=0.02, kt=0.002):
    print("A2 self-consistent single band")
    gs = a2_ground_state(nk, t, filling, u, kt)
    omega = np.linspace(-0.01, 0.04, 1001)
    qs = [2.0 * np.pi * j / nk for j in (0, 4, 10, 20, 40)]   # mesh-commensurate
    print(f"  E_F {gs['ef']:.12f} Ry, M {gs['m']:.12f}, Delta {gs['dlt']:.6f} Ry")

    with open(outdir / "a2_single_band.nml", "w") as fh:
        write_group(fh, "a2_inputs", [
            ("norb", NORB), ("nk", nk), ("t", t), ("filling", filling),
            ("amplitude_rule", "one site; bands are (mu, spin); band (mu,s) has a = 1 at (mu, s), else 0"),
            ("array_dims", "k(nk), w(nk), e_up(nk), e_dn(nk), f_up(nk), f_dn(nk); omega(nomega)"),
            ("u", u), ("kt", kt), ("eta", ETA),
            ("nomega", omega.size), ("omega", omega),
            ("neta_static", len(ETA_STATIC)), ("eta_static", np.array(ETA_STATIC)),
            ("k", gs["k"]), ("w", gs["w"]),
            ("e_up", gs["eu"]), ("e_dn", gs["ed"]),
            ("f_up", gs["fu"]), ("f_dn", gs["fd"]),
            ("nq", len(qs)),
        ])
        write_group(fh, "a2_ground_expected", [
            ("ef", gs["ef"]), ("moment", gs["m"]), ("splitting", gs["dlt"]),
            ("u_goldstone_exact", u), ("u_mills", gs["dlt"] / gs["m"]),
        ])
        for iq, q in enumerate(qs, start=1):
            chi0, st0, edq, fdq, de, weight = a2_chi0(gs, q, t, omega, ETA, kt)
            chi = chi0 / (1.0 + chi0 * u)
            ladder = np.array([lehmann_pairs(gs["w"], de, weight, np.array([0.0]), e)[0]
                               for e in ETA_STATIC])
            mag, wcont = a2_magnon(gs, q, t, u, kt)
            wm = window_moment(gs["w"], de, weight, ETA, omega[0], omega[-1])
            full = float((gs["w"] * weight).sum())        # full-line zeroth moment
            if iq == 1:
                check("Goldstone: chi0(0,0) U M + M, relative",
                      (st0 * u * gs["m"] + gs["m"]) / gs["m"], 1e-12)
                check("zeroth moment over the full line minus M, relative",
                      (full - gs["m"]) / gs["m"], 1e-12)
            print(f"  q={q:.5f}: magnon {mag:.8f} Ry, continuum edge {wcont:.6f} Ry, "
                  f"chi0(q,0) eta=0 {st0:.8f}")
            write_group(fh, "a2_q", [
                ("iq", iq), ("q", q),
                ("e_dn_kq", edq), ("f_dn_kq", fdq),
                ("chi0_re", chi0.real), ("chi0_im", chi0.imag),
                ("chi_re", chi.real), ("chi_im", chi.imag),
                ("chi0_static_eta0", st0),
                ("chi0_static_ladder_re", ladder.real),
                ("chi0_static_ladder_im", ladder.imag),
                ("magnon_eta0", mag), ("continuum_edge", wcont),
                ("chi0_window_moment", wm), ("chi0_full_moment", full),
            ])
    return gs


# ----------------------------------------------------------------------------
# A3: A2 on a doubled cell (sites at x = 0 and x = 1, cell length 2)
# ----------------------------------------------------------------------------
def cell_bands(kc, t, dlt, spin_sign):
    """Eigenvalues and site amplitudes of the 2x2 cell Hamiltonian, periodic gauge."""
    nkc = kc.size
    e = np.empty((nkc, 2))
    v = np.empty((nkc, 2, 2), dtype=complex)       # (k, site, band)
    for j, K in enumerate(kc):
        h01 = -t * (1.0 + np.exp(-2j * K))
        h = np.array([[0.0, h01], [np.conj(h01), 0.0]]) + spin_sign * 0.5 * dlt * np.eye(2)
        ev, vec = np.linalg.eigh(h)
        e[j], v[j] = ev, vec
    return e, v


def model_a3(outdir, gs, t=0.05, kt=0.002):
    print("A3 doubled cell")
    # Goldstone-consistent U for one orbital per site: splitting / moment per orbital
    u = gs["dlt"] / (gs["m"] / NORB)
    nk = gs["k"].size
    nkc = nk // 2
    kc = 2.0 * np.pi * np.arange(nkc) / nk         # cell BZ [0, pi), folds exactly
    wc = np.full(nkc, 1.0 / nkc)
    gsup = np.pi
    rng = np.random.default_rng(20261004)
    omega = np.linspace(-0.01, 0.04, 501)
    qs = [2.0 * np.pi * j / nk for j in (0, 4, 10)]

    def amplitudes(kpts):
        """Bands ordered (up band 1, up band 2, dn band 1, dn band 2) x NORB_A3 copies.

        a(band, mu, site, spin); random phase per band (gauge test).
        """
        eu, vu = cell_bands(kpts, t, gs["dlt"], -1.0)
        ed, vd = cell_bands(kpts, t, gs["dlt"], +1.0)
        nb = 4 * NORB_A3
        e = np.empty((kpts.size, nb))
        a = np.zeros((kpts.size, nb, NORB_A3, 2, 2), dtype=complex)
        for mu in range(NORB_A3):
            for b in range(2):
                ph = np.exp(2j * np.pi * rng.random((kpts.size, 2)))
                iu = 4 * mu + b
                idn = 4 * mu + 2 + b
                e[:, iu], e[:, idn] = eu[:, b], ed[:, b]
                a[:, iu, mu, :, 0] = vu[:, :, b] * ph[:, 0:1]
                a[:, idn, mu, :, 1] = vd[:, :, b] * ph[:, 1:2]
        return e, a

    e_k, a_k = amplitudes(kc)
    f_k = fermi(e_k, gs["ef"], kt)

    with open(outdir / "a3_doubled_cell.nml", "w") as fh:
        write_group(fh, "a3_inputs", [
            ("norb", NORB_A3), ("nsite", 2), ("nband", 4 * NORB_A3), ("nk", nkc),
            ("array_dims", "e(nk,nband), f(nk,nband), a_re/a_im(nk,nband,norb,nsite,2); spin 1=up 2=dn"),
            ("gauge", "periodic gauge, random phase per band and k-point"),
            ("u", u), ("kt", kt), ("eta", ETA), ("ef", gs["ef"]),
            ("nomega", omega.size), ("omega", omega),
            ("k", kc), ("w", wc), ("e", e_k), ("f", f_k),
            ("a_re", a_k.real), ("a_im", a_k.imag),
            ("nq", len(qs)),
        ])
        for iq, Q in enumerate(qs, start=1):
            e_kq, a_kq = amplitudes(kc + Q)
            f_kq = fermi(e_kq, gs["ef"], kt)
            # cell chi0_ij from the spec formula, all band pairs
            chi0 = np.zeros((omega.size, 2, 2), dtype=complex)
            for j in range(nkc):
                # T_i^{nm} = sum_mu conj(a^n_{i mu up}) a^m_{i mu dn}  -> (n, m, site)
                tt = (np.conj(a_k[j][:, None, :, :, 0])
                      * a_kq[j][None, :, :, :, 1]).sum(axis=2)
                fn = f_k[j][:, None] - f_kq[j][None, :]
                de = e_k[j][:, None] - e_kq[j][None, :]
                num = wc[j] * fn[..., None, None] * tt[..., :, None] * np.conj(tt[..., None, :])
                den = omega[:, None, None] + de[None, :, :] + 1j * ETA
                chi0 += np.einsum("wnm,nmij->wij", 1.0 / den, num)
            ident = np.eye(2)
            det = np.array([np.linalg.det(ident + c * u) for c in chi0])
            tr_chi = np.array([np.trace(np.linalg.solve(ident + c * u, c)) for c in chi0])
            tr_l = -tr_chi.imag / np.pi
            # primitive references at Q and Q + G_super (the oracle)
            c1 = a2_chi0(gs, Q, t, omega, ETA, kt)[0] / NORB * NORB_A3
            c2 = a2_chi0(gs, Q + gsup, t, omega, ETA, kt)[0] / NORB * NORB_A3
            det_ref = (1.0 + u * c1) * (1.0 + u * c2)
            tr_ref = c1 / (1.0 + u * c1) + c2 / (1.0 + u * c2)
            scale = np.max(np.abs(tr_ref))
            check(f"Q={Q:.4f}: cell tr chi vs primitive chi(Q)+chi(Q+G)",
                  np.max(np.abs(tr_chi - tr_ref)) / scale, 1e-11)
            check(f"Q={Q:.4f}: cell det(I+chi0 U) vs primitive product",
                  np.max(np.abs(det - det_ref)) / np.max(np.abs(det_ref)), 1e-11)
            write_group(fh, "a3_q", [
                ("iq", iq), ("q", Q), ("g_super", gsup),
                ("e_kq", e_kq), ("f_kq", f_kq),
                ("a_kq_re", a_kq.real), ("a_kq_im", a_kq.imag),
                ("chi0_prim_q_re", c1.real), ("chi0_prim_q_im", c1.imag),
                ("chi0_prim_qg_re", c2.real), ("chi0_prim_qg_im", c2.imag),
                ("tr_chi_re", tr_ref.real), ("tr_chi_im", tr_ref.imag),
                ("tr_spectral", -tr_ref.imag / np.pi),
                ("det_re", det_ref.real), ("det_im", det_ref.imag),
            ])


def main():
    outdir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("out")
    outdir.mkdir(parents=True, exist_ok=True)
    model_a1(outdir)
    gs = model_a2(outdir)
    model_a3(outdir, gs)
    print(f"written to {outdir}/")


if __name__ == "__main__":
    main()

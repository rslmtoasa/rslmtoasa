#!/usr/bin/env python3
"""Analytic reference A5 for NC-1: two-sublattice antiferromagnet and ferrimagnet.

Developer-owned oracle, next to make_references.py (A1-A3) and
make_references_3d.py (A4, R1), which it does not change. Generated by this
script, reviewed by the developer, committed under tests/spin_response/oracles/,
read-only to AI sessions. Only numpy is needed.

Model: a 1-D chain, two sites per cell (A at 0, B at 1/2, cell length 1), one
orbital per site, nearest-neighbour hopping t between A and B,
h_AB(k) = -t (1 + exp(-i k)). Site energy eps_i, Stoner exchange U_i, solved
self-consistently at half filling (two electrons per cell):
    H_up = diag(eps_i - Delta_i/2) + hop,  H_dn = diag(eps_i + Delta_i/2) + hop,
    Delta_i = U_i m_i,  m_i SIGNED (site B negative).
Frame: GLOBAL. Spin label 1 = up along the global axis; nothing is relabelled.

Sets:
  a5_af.nml     eps_A = eps_B, U_A = U_B: antiferromagnet, m_B = -m_A.
                Every up band is degenerate with a down band; the exported
                amplitudes MIX each degenerate pair by a random unitary, as a
                spinor eigensolver may return them. The references are computed
                from the unmixed bands.
  a5_ferri.nml  eps_B > eps_A, U_B < U_A, 1.8 electrons per cell: a METALLIC
                ferrimagnet, |m_B| < |m_A| with a net moment. (At half filling
                with one orbital per site an insulator holds one band per spin,
                so the moments compensate exactly even for inequivalent sites;
                a net moment needs a partly filled band.)

Exact anchors (any mesh, any temperature, self-consistent state):
  chi0(0,0) Delta = -m                 per site, signed
  (1 + chi0(0,0) U) m = 0              the Goldstone zero along the signed m
  U from the Goldstone condition = the model's U_i
  zeroth moment of -Im chi0_ii / pi over the full line = m_i (signed)
Expected physics (measured here, reported, not exact):
  antiferromagnet: adiabatic Omega(q) eigenvalues come in pairs +w, -w, and
  w is LINEAR in q at small q (exponent 1);
  ferrimagnet: one gapless branch QUADRATIC in q (exponent 2) and one gapped
  optical branch.
Adiabatic dispersion: Omega(q) = -N (chi0(q,0)^-1 + U), N = diag(m_i) signed.
At q = 0 for the antiferromagnet Omega is nilpotent (both eigenvalues 0, a
Jordan block): compare Omega only at q != 0 there.

Suggested tolerance keys (the developer sets the values):
  a5_rel            1e-10 (chi0, chi arrays, static chi0, Omega eigenvalues)
  a5_identity_rel   1e-12 (Goldstone identity, U, zeroth moments)
  a5_exponent_abs   physics bound on |p - 1| (AF) and |p - 2| (ferri acoustic)

Usage: python3 make_references_nc.py [outdir]
"""
import sys
from pathlib import Path

import numpy as np

ETA = 1.0e-3
NK = 160
QJ = (0, 1, 2, 4)                 # q = 2 pi j / NK: q = 0 and the ladder q, 2q, 4q
OMEGA = np.linspace(-0.08, 0.08, 161)

SETS = {
    "af": dict(t=0.05, eps=(0.0, 0.0), U=(0.15, 0.15), nel=2.0, kt=0.002, m0=(0.6, -0.6)),
    "ferri": dict(t=0.05, eps=(0.0, 0.05), U=(0.15, 0.10), nel=1.8, kt=0.002, m0=(0.6, -0.4)),
}


# ----------------------------------------------------------------------------
# helpers (as in the other generators)
# ----------------------------------------------------------------------------
def fermi(e, ef, kt):
    return 0.5 * (1.0 - np.tanh(0.5 * (e - ef) / kt))


def bisect(fun, a, b, tol=1e-15, itmax=300):
    fa = fun(a)
    for _ in range(itmax):
        c = 0.5 * (a + b)
        fc = fun(c)
        if (fc > 0) == (fa > 0):
            a, fa = c, fc
        else:
            b = c
        if b - a < tol:
            break
    return 0.5 * (a + b)


def nml_value(v):
    if isinstance(v, (bool, np.bool_)):
        return ".true." if v else ".false."
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    return f"{float(v):.17e}"


def write_group(fh, name, items):
    fh.write(f"&{name}\n")
    for key, val in items:
        arr = np.asarray(val)
        if arr.ndim == 0:
            fh.write(f"  {key} = {nml_value(val)}\n")
        else:
            flat = arr.ravel(order="F")
            fh.write(f"  {key} =\n")
            for i in range(0, flat.size, 4):
                fh.write("    " + ", ".join(nml_value(x) for x in flat[i:i + 4]) + ",\n")
    fh.write("/\n\n")


def check(label, value, tol):
    status = "ok" if abs(value) <= tol else "FAIL"
    print(f"  [{status}] {label}: {value:.3e} (tol {tol:.0e})")
    if status == "FAIL":
        raise SystemExit(f"self-check failed: {label}")


# ----------------------------------------------------------------------------
# model
# ----------------------------------------------------------------------------
def hk(k, p, dvec, sgn):
    """sgn = -1 (up) or +1 (down); exchange field diag(dvec)/2 with signed dvec."""
    h = np.zeros((k.size, 2, 2), dtype=complex)
    h[:, 0, 0] = p["eps"][0] + sgn * 0.5 * dvec[0]
    h[:, 1, 1] = p["eps"][1] + sgn * 0.5 * dvec[1]
    h[:, 0, 1] = -p["t"] * (1.0 + np.exp(-1j * k))
    h[:, 1, 0] = np.conj(h[:, 0, 1])
    return h


def ground_state(p):
    k = 2 * np.pi * np.arange(NK) / NK
    w = np.full(NK, 1.0 / NK)
    U = np.array(p["U"])
    m = np.array(p["m0"], dtype=float)
    for _ in range(20000):
        dvec = U * m
        eu, vu = np.linalg.eigh(hk(k, p, dvec, -1.0))
        ed, vd = np.linalg.eigh(hk(k, p, dvec, +1.0))
        def nerr(ef):
            return (w[:, None] * (fermi(eu, ef, p["kt"]) + fermi(ed, ef, p["kt"]))).sum() - p["nel"]
        ef = bisect(nerr, min(eu.min(), ed.min()) - 1, max(eu.max(), ed.max()) + 1)
        fu, fd = fermi(eu, ef, p["kt"]), fermi(ed, ef, p["kt"])
        mnew = np.array([(w[:, None] * (fu * abs(vu[:, i, :]) ** 2 - fd * abs(vd[:, i, :]) ** 2)).sum()
                         for i in range(2)])
        if np.max(abs(mnew - m)) < 1e-15:
            m = mnew
            break
        m = 0.5 * m + 0.5 * mnew
    return dict(k=k, w=w, ef=ef, m=m, U=U, dvec=U * m, kt=p["kt"])


def endpoint(gs, p, kpts):
    """Unmixed bands (up 1, up 2, dn 1, dn 2) and amplitudes a(k, band, orb=1, site=2, spin=2)."""
    eu, vu = np.linalg.eigh(hk(kpts, p, gs["dvec"], -1.0))
    ed, vd = np.linalg.eigh(hk(kpts, p, gs["dvec"], +1.0))
    e = np.concatenate([eu, ed], axis=1)
    f = fermi(e, gs["ef"], gs["kt"])
    a = np.zeros((kpts.size, 4, 1, 2, 2), dtype=complex)
    for b in range(2):
        a[:, b, 0, :, 0] = vu[:, :, b]
        a[:, 2 + b, 0, :, 1] = vd[:, :, b]
    return e, f, a


def mix_pairs(e, f, a, rng, degenerate):
    """Random phase per band; for degenerate (up b, dn b) pairs a random unitary mix."""
    e, f, a = e.copy(), f.copy(), a.copy()
    nk = e.shape[0]
    a *= np.exp(2j * np.pi * rng.random((nk, 4)))[:, :, None, None, None]
    if degenerate:
        for b in range(2):
            gap = np.max(np.abs(e[:, b] - e[:, 2 + b]))
            if gap > 1e-12:
                raise SystemExit(f"band pair {b} not degenerate: {gap:.2e}")
            ebar = 0.5 * (e[:, b] + e[:, 2 + b])
            e[:, b] = e[:, 2 + b] = ebar
            f[:, b] = f[:, 2 + b] = 0.5 * (f[:, b] + f[:, 2 + b])
            for ik in range(nk):
                z = rng.normal(size=(2, 2)) + 1j * rng.normal(size=(2, 2))
                qmat, r = np.linalg.qr(z)
                qmat = qmat * (np.diag(r) / np.abs(np.diag(r)))     # Haar unitary
                pair = np.stack([a[ik, b], a[ik, 2 + b]])            # (2, orb, site, spin)
                mixed = np.tensordot(qmat, pair, axes=(1, 0))
                a[ik, b], a[ik, 2 + b] = mixed[0], mixed[1]
    return e, f, a


def chi0(w, ek, fk, ak, eq, fq, aq, omega, eta, kt):
    """chi0_ij(omega) by the spec formula; T_i = conj(a_{n,i,up}(k)) a_{m,i,dn}(k+q)."""
    nb = ek.shape[1]
    out = np.zeros((omega.size, 2, 2), dtype=complex)
    for n in range(nb):
        for m in range(nb):
            T = np.conj(ak[:, n, 0, :, 0]) * aq[:, m, 0, :, 1]
            if not np.any(T):
                continue
            de = ek[:, n] - eq[:, m]
            fn, fm = fk[:, n], fq[:, m]
            P = np.einsum("k,ka,kb->kab", w, T, np.conj(T))
            if eta == 0.0:
                big = np.abs(de) > 1e-10
                c = np.where(big, (fn - fm) / np.where(big, de, 1.0), -fn * (1 - fn) / kt)
                out[0] += np.einsum("k,kab->ab", c, P)
            else:
                c = (fn - fm)[None, :] / (omega[:, None] + de[None, :] + 1j * eta)
                out += np.einsum("wk,kab->wab", c, P)
    return out


def zeroth_moment(w, fk, ak, fq, aq):
    mom = np.zeros(2)
    for n in range(4):
        for m in range(4):
            T = np.conj(ak[:, n, 0, :, 0]) * aq[:, m, 0, :, 1]
            mom += (w[:, None] * (fk[:, n] - fq[:, m])[:, None] * np.abs(T) ** 2).sum(0)
    return mom


def omega_adiabatic(st, U, m):
    om = -np.diag(m) @ (np.linalg.inv(st) + np.diag(U))
    return np.linalg.eigvals(om)


def build(name, p, outdir, rng):
    print(f"A5 {name}")
    gs = ground_state(p)
    m, U, dvec = gs["m"], gs["U"], gs["dvec"]
    degenerate = name == "af"
    if degenerate:
        check("antiferromagnet: m_A + m_B", m[0] + m[1], 1e-12)
    print(f"  E_F {gs['ef']:.12f} Ry, m = ({m[0]:+.10f}, {m[1]:+.10f}), Delta = ({dvec[0]:+.6f}, {dvec[1]:+.6f})")

    ek0, fk0, ak0 = endpoint(gs, p, gs["k"])
    ek, fk, ak = mix_pairs(ek0, fk0, ak0, rng, degenerate)

    # stability over every q of the mesh, static, eta = 0
    mins, maxim = [], 0.0
    for j in range(1, NK // 2 + 1):
        eq0, fq0, aq0 = endpoint(gs, p, gs["k"] + 2 * np.pi * j / NK)
        st = chi0(gs["w"], ek0, fk0, ak0, eq0, fq0, aq0, np.array([0.0]), 0.0, gs["kt"])[0]
        mins.append(np.min(np.linalg.eigvals(np.eye(2) + st @ np.diag(U)).real))
        maxim = max(maxim, np.max(np.abs(omega_adiabatic(st, U, m).imag)))
    print(f"  stability: min over q > 0 of eig(1 + chi0(q,0) U) = {min(mins):+.4e}; "
          f"max |Im Omega| over q > 0 = {maxim:.1e}")
    if min(mins) <= 0:
        raise SystemExit(f"A5 {name}: unstable state")

    ladder = {}
    with open(outdir / f"a5_{name}.nml", "w") as fh:
        write_group(fh, "a5_inputs", [
            ("set", name), ("nk", NK), ("nband", 4), ("norb", 1), ("nsite", 2),
            ("t", p["t"]), ("eps", np.array(p["eps"])), ("u_model", U), ("nel", p["nel"]),
            ("kt", p["kt"]), ("eta", ETA), ("ef", gs["ef"]), ("moment", m), ("delta", dvec),
            ("frame", "global; spin 1 = up along the global axis; site B moment negative; nothing relabelled"),
            ("array_dims", "e(nk,nband), f(nk,nband), a_re/a_im(nk,nband,norb,nsite,2)"),
            ("gauge", "random phase per band and k; degenerate up/down pairs randomly mixed (af set)"),
            ("nomega", OMEGA.size), ("omega", OMEGA),
            ("k", gs["k"]), ("w", gs["w"]), ("e", ek), ("f", fk),
            ("a_re", ak.real), ("a_im", ak.imag), ("nq", len(QJ)),
        ])
        for iq, j in enumerate(QJ, start=1):
            q = 2 * np.pi * j / NK
            eq0, fq0, aq0 = endpoint(gs, p, gs["k"] + q)
            eq, fq, aq = mix_pairs(eq0, fq0, aq0, rng, degenerate)
            c0 = chi0(gs["w"], ek0, fk0, ak0, eq0, fq0, aq0, OMEGA, ETA, gs["kt"])
            st = chi0(gs["w"], ek0, fk0, ak0, eq0, fq0, aq0, np.array([0.0]), 0.0, gs["kt"])[0]
            # the exported (mixed) amplitudes must give the same response
            c0x = chi0(gs["w"], ek, fk, ak, eq, fq, aq, OMEGA, ETA, gs["kt"])
            stx = chi0(gs["w"], ek, fk, ak, eq, fq, aq, np.array([0.0]), 0.0, gs["kt"])[0]
            check(f"q={q:.4f}: mixed vs unmixed chi0, relative",
                  np.max(np.abs(c0x - c0)) / np.max(np.abs(c0)), 1e-12)
            check(f"q={q:.4f}: mixed vs unmixed static chi0, relative",
                  np.max(np.abs(stx - st)) / np.max(np.abs(st)), 1e-12)
            chi = np.array([np.linalg.solve(np.eye(2) + c @ np.diag(U), c) for c in c0])
            ev = np.sort(np.linalg.eigvals(np.eye(2) + st @ np.diag(U)).real)
            mom0 = zeroth_moment(gs["w"], fk0, ak0, fq0, aq0)
            check(f"q={q:.4f}: zeroth moment per site minus signed m (E1)",
                  np.max(np.abs(mom0 - m)) / np.max(np.abs(m)), 1e-12)
            items = [("iq", iq), ("q", q), ("e_kq", eq), ("f_kq", fq),
                     ("a_kq_re", aq.real), ("a_kq_im", aq.imag),
                     ("chi0_re", c0.real), ("chi0_im", c0.imag),
                     ("chi_re", chi.real), ("chi_im", chi.imag),
                     ("chi0_static_re", st.real), ("chi0_static_im", st.imag),
                     ("eig_static", ev), ("zeroth_moment", mom0)]
            if j == 0:
                gold = st @ dvec + m
                check("Goldstone identity chi0(0,0) Delta + m, relative",
                      np.max(np.abs(gold)) / np.max(np.abs(m)), 1e-12)
                res = (np.eye(2) + st @ np.diag(U)) @ m
                check("(1 + chi0 U) m with the model U, relative",
                      np.max(np.abs(res)) / np.max(np.abs(m)), 1e-12)
                # the Goldstone condition solved for U (as u_juelich does) returns the model U
                usolve = np.linalg.solve(-st @ np.diag(m), m)        # chi0 diag(m) U = -m
                check("U from the Goldstone condition is real, |Im U| / U",
                      np.max(np.abs(usolve.imag)) / np.max(U), 1e-12)
                usolve = usolve.real
                check("U from the Goldstone condition minus the model U, relative",
                      np.max(np.abs(usolve - U)) / np.max(U), 1e-12)
                items += [("goldstone_residual", np.max(np.abs(res))), ("u_goldstone", usolve)]
                if not degenerate:
                    om = np.sort(omega_adiabatic(st, U, m).real)
                    items += [("omega_adiabatic", om)]
                    ladder[0] = om
                    print(f"  q = 0: Omega eigenvalues {om[0]:+.6e}, {om[1]:+.6e} (Goldstone and optical)")
            else:
                omc = omega_adiabatic(st, U, m)
                check(f"q={q:.4f}: Omega eigenvalues real, |Im| / |Re|",
                      np.max(np.abs(omc.imag)) / np.max(np.abs(omc.real)), 1e-10)
                om = np.sort(omc.real)
                if degenerate:
                    check(f"q={q:.4f}: antiferromagnetic pair, |w+ + w-| / w",
                          abs(om[0] + om[1]) / abs(om[1]), 1e-10)
                items += [("omega_adiabatic", om)]
                ladder[j] = om
            write_group(fh, "a5_q", items)

        # exponents along the ladder q, 2q, 4q
        if degenerate:
            br = np.array([ladder[j][1] for j in (1, 2, 4)])           # the positive branch
            label = "positive branch"
        else:
            # the gapless (acoustic) branch: the eigenvalue that vanishes at q = 0
            iac = int(np.argmin(np.abs(ladder[0])))
            br = np.array([ladder[j][iac] for j in (1, 2, 4)])
            label = "acoustic branch"
            print(f"  optical gap at q = 0: {ladder[0][1 - iac]:+.6e} Ry")
        pexp = np.log2(np.abs(br[1:] / br[:-1]))
        print(f"  {label}: w(q, 2q, 4q) = {br[0]:+.4e}, {br[1]:+.4e}, {br[2]:+.4e}; "
              f"exponents {pexp[0]:.4f}, {pexp[1]:.4f}")
        write_group(fh, "a5_exponent", [("branch", label), ("ladder_j", np.array([1, 2, 4])),
                                        ("omega_branch", br), ("exponent", pexp)])
    return pexp


def main():
    outdir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("out")
    outdir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(20261012)
    p_af = build("af", SETS["af"], outdir, rng)
    p_fe = build("ferri", SETS["ferri"], outdir, rng)
    check("antiferromagnet exponent minus 1 (expected linear)", np.max(np.abs(p_af - 1.0)), 0.05)
    check("ferrimagnet acoustic exponent minus 2 (expected quadratic)", np.max(np.abs(p_fe - 2.0)), 0.05)
    print(f"written to {outdir}/")


if __name__ == "__main__":
    main()

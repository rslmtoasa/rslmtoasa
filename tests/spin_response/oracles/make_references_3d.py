#!/usr/bin/env python3
"""Analytic and semi-analytic references A4 and R1 for the Stage 3d kernel.

Developer-owned oracle, next to make_references.py (A1-A3), which it does not
change. Generated by this script, reviewed by the developer, committed under
tests/spin_response/oracles/, read-only to AI sessions. Only numpy is needed.

Conventions: as A1-A3 (spec, "Conventions"). chi0_ab is indexed by channel
kappa = a; T_a^{nm} = conj(a^{nk}_{a,up}) a^{m,k+q}_{a,dn}; (I + chi0 K) chi =
chi0; energies, omega, eta, K in Ry.

A4  Self-consistent two-channel Stoner ferromagnet on a 1-D chain: an s-like
    broad band and a d-like narrow band, hybridized (V), with an exchange
    MATRIX I: the exchange field is Delta_a = sum_b I_ab m_b, diagonal in the
    channels, and m_a are the channel moments.
    Exact anchors, for any mesh and temperature:
      chi0(0,0) Delta = -m                (the identity behind Goldstone)
      (1 + chi0(0,0) K) m = 0 for K = I   (exact Goldstone, eigenvector m)
      for K = lambda I the eigenvalue along m is exactly 1 - lambda
      the zeroth moment of -Im chi0_aa / pi over the full line equals m_a
    Finite-q chi0 and chi are an independent evaluation of the spec formula.
R1  Radial kernel integrals. Analytic radial functions G = N r^(l+1)
    exp(-alpha r), small components S = s0 G, constant gfac, and
    m(r) = m0 (r - r0) exp(-gamma r), Delta V(r) = -c m0 (r - r0)
    exp(-(gamma + beta) r), so that K(r) = Delta V / m = -c exp(-beta r) is
    smooth through the sign change of m. Exact closed form:
      K_ll' = (1/4 pi) int_0^R dr P_l P_l' / r^2 K(r),
      P_l = sqrt(g_up g_dn) G_up G_dn + S_up S_dn   (the SR metric)
    on the code's exponential mesh r_i = b (exp(a (i-1)) - 1), nr odd.
    Variant R1b puts r0 exactly on a mesh point (0/0 in Delta V / m there):
    the expected integrals are unchanged, so it tests the guard. As in the
    real data, Delta V(r = 0) = 0.

Suggested tolerances (the developer sets the final ones):
  a4_rel           1e-10 relative (chi0, chi arrays; different summation order)
  a4_identity_rel  1e-12 (Goldstone identity, eigenvalues, controls, E1)
  r1_rel           about 10 x the measured Simpson error printed below

Usage: python3 make_references_3d.py [outdir]
"""
import sys
from math import factorial
from pathlib import Path

import numpy as np

ETA = 1.0e-3


# ----------------------------------------------------------------------------
# helpers (namelist writer as in make_references.py)
# ----------------------------------------------------------------------------
def fermi(e, ef, kt):
    return 0.5 * (1.0 - np.tanh(0.5 * (e - ef) / kt))


def bisect(fun, a, b, tol=1e-15, itmax=300):
    fa = fun(a)
    for _ in range(itmax):
        c = 0.5 * (a + b)
        fc = fun(c)
        if (fc > 0) == (fa > 0):
            a, fa = c, fc
        else:
            b = c
        if b - a < tol:
            break
    return 0.5 * (a + b)


def nml_value(v):
    if isinstance(v, (bool, np.bool_)):
        return ".true." if v else ".false."
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"        # Fortran doubles an embedded apostrophe
    return f"{float(v):.17e}"


def write_group(fh, name, items):
    fh.write(f"&{name}\n")
    for key, val in items:
        arr = np.asarray(val)
        if arr.ndim == 0:
            fh.write(f"  {key} = {nml_value(val)}\n")
        else:
            flat = arr.ravel(order="F")
            fh.write(f"  {key} =\n")
            for i in range(0, flat.size, 4):
                fh.write("    " + ", ".join(nml_value(x) for x in flat[i:i + 4]) + ",\n")
    fh.write("/\n\n")


def check(label, value, tol):
    status = "ok" if abs(value) <= tol else "FAIL"
    print(f"  [{status}] {label}: {value:.3e} (tol {tol:.0e})")
    if status == "FAIL":
        raise SystemExit(f"self-check failed: {label}")


# ----------------------------------------------------------------------------
# A4: two-channel Stoner ferromagnet
# ----------------------------------------------------------------------------
A4 = dict(ts=0.15, td=0.03, cs=0.10, cd=-0.05, v=0.06, nel=1.0,
          I=[[0.02, 0.01], [0.01, 0.12]], nk=200, kt=0.002)


def hk(k, p, dvec, sgn):
    """2x2 channel Hamiltonian; sgn = -1 (up) or +1 (down); field diag(dvec)/2."""
    h = np.zeros((k.size, 2, 2))
    h[:, 0, 0] = -2 * p["ts"] * np.cos(k) + p["cs"] + sgn * 0.5 * dvec[0]
    h[:, 1, 1] = -2 * p["td"] * np.cos(k) + p["cd"] + sgn * 0.5 * dvec[1]
    h[:, 0, 1] = h[:, 1, 0] = p["v"]
    return h


def a4_ground_state(p):
    nk, kt = p["nk"], p["kt"]
    k = 2 * np.pi * np.arange(nk) / nk
    w = np.full(nk, 1.0 / nk)
    I = np.array(p["I"])
    m = np.array([0.3, 1.0])
    for _ in range(5000):
        dvec = I @ m
        eu, vu = np.linalg.eigh(hk(k, p, dvec, -1.0))
        ed, vd = np.linalg.eigh(hk(k, p, dvec, +1.0))
        def nerr(ef):
            return (w[:, None] * (fermi(eu, ef, kt) + fermi(ed, ef, kt))).sum() - p["nel"]
        ef = bisect(nerr, min(eu.min(), ed.min()) - 1, max(eu.max(), ed.max()) + 1)
        fu, fd = fermi(eu, ef, kt), fermi(ed, ef, kt)
        mnew = np.array([(w[:, None] * (fu * vu[:, a, :] ** 2 - fd * vd[:, a, :] ** 2)).sum()
                         for a in range(2)])
        if np.max(abs(mnew - m)) < 1e-15:
            m = mnew
            break
        m = 0.7 * m + 0.3 * mnew
    dvec = I @ m
    eu, vu = np.linalg.eigh(hk(k, p, dvec, -1.0))
    ed, vd = np.linalg.eigh(hk(k, p, dvec, +1.0))
    return dict(k=k, w=w, ef=ef, m=m, dvec=dvec, I=I, kt=kt, eu=eu, vu=vu, ed=ed, vd=vd,
                fu=fermi(eu, ef, kt), fd=fermi(ed, ef, kt))


def a4_endpoint(gs, p, kpts):
    """Bands (up 1, up 2, dn 1, dn 2) and amplitudes a(k, band, orb=1, kappa=2, spin=2)."""
    eu, vu = np.linalg.eigh(hk(kpts, p, gs["dvec"], -1.0))
    ed, vd = np.linalg.eigh(hk(kpts, p, gs["dvec"], +1.0))
    e = np.concatenate([eu, ed], axis=1)
    f = fermi(e, gs["ef"], gs["kt"])
    a = np.zeros((kpts.size, 4, 1, 2, 2), dtype=complex)
    for b in range(2):
        a[:, b, 0, :, 0] = vu[:, :, b]
        a[:, 2 + b, 0, :, 1] = vd[:, :, b]
    return e, f, a


def a4_chi0(w, e_k, f_k, a_k, e_kq, f_kq, a_kq, omega, eta, kt):
    """chi0_ab(omega) by the spec formula; eta = 0 only at omega = 0 (divided differences)."""
    nb = e_k.shape[1]
    chi = np.zeros((omega.size, 2, 2), dtype=complex)
    for n in range(nb):
        for m in range(nb):
            T = np.conj(a_k[:, n, 0, :, 0]) * a_kq[:, m, 0, :, 1]          # (k, kappa)
            if not np.any(T):
                continue
            de = e_k[:, n] - e_kq[:, m]
            fn, fm = f_k[:, n], f_kq[:, m]
            P = np.einsum("k,ka,kb->kab", w, T, np.conj(T))
            if eta == 0.0:
                big = np.abs(de) > 1e-10
                c = np.where(big, (fn - fm) / np.where(big, de, 1.0), -fn * (1 - fn) / kt)
                chi[0] += np.einsum("k,kab->ab", c, P)
            else:
                c = (fn - fm)[None, :] / (omega[:, None] + de[None, :] + 1j * eta)
                chi += np.einsum("wk,kab->wab", c, P)
    return chi


def model_a4(outdir):
    print("A4 two-channel Stoner ferromagnet")
    p = A4
    gs = a4_ground_state(p)
    rng = np.random.default_rng(20261011)
    def phased(e, f, a):
        ph = np.exp(2j * np.pi * rng.random((a.shape[0], a.shape[1])))
        return e, f, a * ph[:, :, None, None, None]
    e_k, f_k, a_k = phased(*a4_endpoint(gs, p, gs["k"]))
    nk = gs["k"].size
    omega = np.linspace(0.0, 0.08, 161)
    K = gs["I"]
    m, dvec = gs["m"], gs["dvec"]
    nup = np.array([(gs["w"][:, None] * gs["fu"] * gs["vu"][:, a, :] ** 2).sum() for a in range(2)])
    ndn = np.array([(gs["w"][:, None] * gs["fd"] * gs["vd"][:, a, :] ** 2).sum() for a in range(2)])
    print(f"  E_F {gs['ef']:.12f} Ry, m = ({m[0]:+.10f}, {m[1]:.10f}), "
          f"n_up = ({nup[0]:.3f}, {nup[1]:.3f}), n_dn = ({ndn[0]:.3f}, {ndn[1]:.3f})")

    # stability over every q of the mesh (static, eta = 0)
    mins = []
    for j in range(1, nk // 2 + 1):
        q = 2 * np.pi * j / nk
        eq, fq, aq = a4_endpoint(gs, p, gs["k"] + q)
        c0 = a4_chi0(gs["w"], e_k, f_k, a_k, eq, fq, aq, np.array([0.0]), 0.0, gs["kt"])[0]
        mins.append(np.min(np.linalg.eigvals(np.eye(2) + c0 @ K).real))
    print(f"  stability: min over q > 0 of the eigenvalues of 1 + chi0(q,0) K = {min(mins):+.4e}")
    if min(mins) <= 0:
        raise SystemExit("A4 parameters give an unstable ferromagnet")

    qs = [2 * np.pi * j / nk for j in (0, 2, 10, 40)]
    with open(outdir / "a4_two_channel.nml", "w") as fh:
        write_group(fh, "a4_inputs", [
            ("nk", nk), ("nband", 4), ("norb", 1), ("nkappa", 2),
            ("ts", p["ts"]), ("td", p["td"]), ("cs", p["cs"]), ("cd", p["cd"]),
            ("v", p["v"]), ("nel", p["nel"]), ("kt", p["kt"]), ("eta", ETA),
            ("kernel", K), ("ef", gs["ef"]), ("moment", m), ("delta", dvec),
            ("array_dims", "e(nk,nband), f(nk,nband), a_re/a_im(nk,nband,norb,nkappa,2); "
                           "bands up1 up2 dn1 dn2; kappa 1 = s-like, 2 = d-like; spin 1 = up"),
            ("gauge", "random phase per band and k-point"),
            ("nomega", omega.size), ("omega", omega),
            ("k", gs["k"]), ("w", gs["w"]), ("e", e_k), ("f", f_k),
            ("a_re", a_k.real), ("a_im", a_k.imag), ("nq", len(qs)),
        ])
        for iq, q in enumerate(qs, start=1):
            e_q, f_q, a_q = phased(*a4_endpoint(gs, p, gs["k"] + q))
            c0 = a4_chi0(gs["w"], e_k, f_k, a_k, e_q, f_q, a_q, omega, ETA, gs["kt"])
            chi = np.array([np.linalg.solve(np.eye(2) + c @ K, c) for c in c0])
            st = a4_chi0(gs["w"], e_k, f_k, a_k, e_q, f_q, a_q, np.array([0.0]), 0.0, gs["kt"])[0]
            ev = np.sort(np.linalg.eigvals(np.eye(2) + st @ K).real)
            # full-line zeroth moment of -Im chi0_aa / pi = sum of weights (f_n - f_m) |T_a|^2
            mom0 = np.zeros(2)
            for n in range(4):
                for mm in range(4):
                    T = np.conj(a_k[:, n, 0, :, 0]) * a_q[:, mm, 0, :, 1]
                    mom0 += (gs["w"][:, None] * (f_k[:, n] - f_q[:, mm])[:, None] * np.abs(T) ** 2).sum(0)
            check(f"q={q:.4f}: zeroth moment per channel minus m (E1)",
                  np.max(np.abs(mom0 - m)) / np.max(np.abs(m)), 1e-12)
            items = [("iq", iq), ("q", q), ("e_kq", e_q), ("f_kq", f_q),
                     ("a_kq_re", a_q.real), ("a_kq_im", a_q.imag),
                     ("chi0_re", c0.real), ("chi0_im", c0.imag),
                     ("chi_re", chi.real), ("chi_im", chi.imag),
                     ("chi0_static_re", st.real), ("chi0_static_im", st.imag),
                     ("eig_static", ev), ("zeroth_moment", mom0)]
            if iq == 1:
                gold = st @ dvec + m
                check("Goldstone identity chi0(0,0) Delta + m, relative",
                      np.max(np.abs(gold)) / np.max(np.abs(m)), 1e-12)
                lam_m = (np.eye(2) + st @ K) @ m
                check("(1 + chi0 K) m for K = I, relative", np.max(np.abs(lam_m)) / np.max(np.abs(m)), 1e-12)
                ctrl = []
                for lam in (2.0, 0.5):
                    r = (np.eye(2) + lam * st @ K) @ m - (1 - lam) * m
                    check(f"control K = {lam} I: eigenvalue 1 - lambda along m",
                          np.max(np.abs(r)) / np.max(np.abs(m)), 1e-12)
                    ctrl.append(1 - lam)
                items += [("goldstone_residual", np.max(np.abs(gold))),
                          ("control_lambda", np.array([2.0, 0.5])),
                          ("control_eigenvalue_along_m", np.array(ctrl))]
                print(f"  q = 0 eigenvalues of 1 + chi0 K: {ev[0]:+.3e}, {ev[1]:+.6f}")
            write_group(fh, "a4_q", items)
    return gs


# ----------------------------------------------------------------------------
# R1: radial kernel integrals with a closed form
# ----------------------------------------------------------------------------
R1 = dict(nr=495, a=0.02, rmax=2.6622, lmax=3,
          alpha_up=[2.2, 1.9, 1.6, 1.3], alpha_dn=[2.31, 1.995, 1.68, 1.365],
          g_up=[1.010, 1.020, 1.030, 1.040], g_dn=[1.011, 1.022, 1.033, 1.044],
          s0_up=[0.020, 0.018, 0.016, 0.014], s0_dn=[0.021, 0.019, 0.017, 0.015],
          m0=0.8, r0=1.37, gamma=1.1, c=4.0, beta=0.7)


def lower_gamma_int(n, x):
    """gamma(n, x) for integer n >= 1: (n-1)! [1 - e^-x sum_{k<n} x^k/k!]."""
    s = sum(x ** k / factorial(k) for k in range(n))
    return factorial(n - 1) * (1.0 - np.exp(-x) * s)


def mesh(p):
    nr, a = p["nr"], p["a"]
    b = p["rmax"] / (np.exp(a * (nr - 1)) - 1.0)
    r = b * (np.exp(a * np.arange(nr)) - 1.0)
    wsimp = np.ones(nr)
    wsimp[1:-1:2] = 4.0
    wsimp[2:-1:2] = 2.0
    return r, b, wsimp / 3.0 * a * (r + b)        # Simpson in i, times dr/di


def model_r1(outdir):
    print("R1 radial kernel integrals")
    p = R1
    r, b, wq = mesh(p)
    R = r[-1]
    L = p["lmax"]
    G = {}
    S = {}
    N = {}
    cfac = np.zeros(L + 1)
    for l in range(L + 1):
        for sp, al, g, s0 in (("up", p["alpha_up"][l], p["g_up"][l], p["s0_up"][l]),
                              ("dn", p["alpha_dn"][l], p["g_dn"][l], p["s0_dn"][l])):
            n = 2 * l + 3
            N[l, sp] = ((g + s0 ** 2) * lower_gamma_int(n, 2 * al * R) / (2 * al) ** n) ** -0.5
            G[l, sp] = N[l, sp] * r ** (l + 1) * np.exp(-al * r)
            S[l, sp] = s0 * G[l, sp]
            nerr = (wq * (g * G[l, sp] ** 2 + S[l, sp] ** 2)).sum() - 1.0
            print(f"  l={l} {sp}: Simpson error of the exact normalization: {nerr:+.2e}")
            check(f"l={l} {sp}: Simpson normalization error, sanity bound", nerr, 1e-5)
        cfac[l] = np.sqrt(p["g_up"][l] * p["g_dn"][l]) + p["s0_up"][l] * p["s0_dn"][l]

    def density_and_field(r0):
        mr = p["m0"] * (r - r0) * np.exp(-p["gamma"] * r)
        dv = -p["c"] * p["m0"] * (r - r0) * np.exp(-(p["gamma"] + p["beta"]) * r)
        dv[0] = 0.0                                   # as in the real data
        return mr, dv

    kexact = np.zeros((L + 1, L + 1))
    ksimp = np.zeros((L + 1, L + 1))
    kr = -p["c"] * np.exp(-p["beta"] * r)
    for l in range(L + 1):
        for lp in range(L + 1):
            al = p["alpha_up"][l] + p["alpha_dn"][l] + p["alpha_up"][lp] + p["alpha_dn"][lp]
            npow = 2 * l + 2 * lp + 2
            lam = al + p["beta"]
            C = cfac[l] * cfac[lp] * N[l, "up"] * N[l, "dn"] * N[lp, "up"] * N[lp, "dn"]
            kexact[l, lp] = -p["c"] / (4 * np.pi) * C * lower_gamma_int(npow + 1, lam * R) / lam ** (npow + 1)
            Pl = cfac[l] * G[l, "up"] * G[l, "dn"]
            Plp = cfac[lp] * G[lp, "up"] * G[lp, "dn"]
            integrand = np.zeros_like(r)
            integrand[1:] = Pl[1:] * Plp[1:] / r[1:] ** 2 * kr[1:]
            ksimp[l, lp] = (wq * integrand).sum() / (4 * np.pi)
    err = np.max(np.abs(ksimp - kexact) / np.abs(kexact))
    print(f"  Simpson on the mesh vs exact K_ll': max relative error {err:.2e}")
    check("K_ll' symmetric, relative", np.max(np.abs(kexact - kexact.T)) / np.max(np.abs(kexact)), 1e-14)

    # main data set: r0 between mesh points; variant b: r0 on a mesh point
    i0 = int(np.argmin(np.abs(r - p["r0"])))
    r0_between = 0.5 * (r[i0] + r[i0 + 1])
    r0_on = r[i0]
    with open(outdir / "r1_radial_kernel.nml", "w") as fh:
        write_group(fh, "r1_mesh", [
            ("nr", p["nr"]), ("a", p["a"]), ("b", b), ("lmax", L), ("ncase", 2),
            ("array_dims", "g_up/g_dn/s_up/s_dn(nr, 0:lmax); kernel(0:lmax, 0:lmax)"),
            ("definition", "K_ll' = (1/4 pi) int dr P_l P_l' K / r^2, P_l = sqrt(gfac_up gfac_dn) G_up G_dn + S_up S_dn, K = dV/m"),
            ("r", r),
            ("gfac_up", np.array(p["g_up"])), ("gfac_dn", np.array(p["g_dn"])),
            ("g_up", np.stack([G[l, "up"] for l in range(L + 1)], axis=1)),
            ("g_dn", np.stack([G[l, "dn"] for l in range(L + 1)], axis=1)),
            ("s_up", np.stack([S[l, "up"] for l in range(L + 1)], axis=1)),
            ("s_dn", np.stack([S[l, "dn"] for l in range(L + 1)], axis=1))])
        for icase, r0 in ((1, r0_between), (2, r0_on)):
            mr, dv = density_and_field(r0)
            kpts = np.where(np.abs(mr) > 0, dv / np.where(np.abs(mr) > 0, mr, 1.0), np.nan)
            ok = np.isfinite(kpts) & (np.arange(r.size) > 0)
            check(f"case {icase}: dV/m = -c exp(-beta r) where defined, relative",
                  np.max(np.abs(kpts[ok] - kr[ok]) / np.abs(kr[ok])), 1e-12)
            write_group(fh, "r1_case", [
                ("icase", icase), ("r0", r0), ("r0_on_mesh_point", icase == 2),
                ("k_at_r0_limit", -p["c"] * np.exp(-p["beta"] * r0)),
                ("m_of_r", mr), ("dv_of_r", dv)])
        write_group(fh, "r1_expected", [
            ("kernel_exact", kexact), ("kernel_simpson_reference", ksimp),
            ("simpson_max_rel_error", err)])
    print(f"  K_ll' (Ry): diag {np.round(np.diag(kexact), 5)}")
    return kexact


def main():
    outdir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("out")
    outdir.mkdir(parents=True, exist_ok=True)
    model_a4(outdir)
    model_r1(outdir)
    print(f"written to {outdir}/")


if __name__ == "__main__":
    main()

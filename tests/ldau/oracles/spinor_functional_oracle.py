#!/usr/bin/env python3
"""Independent full-spinor d-shell HF/FLL algebra oracle (no production imports).

The orbital tensor is generated by the SymPy complex-harmonic reference.  The
spinor density uses spin-major order, five m=-2..2 orbitals per spin.
"""
from __future__ import annotations

import numpy as np

from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ldau_tensor_reference import tensor


NORB = 5
NSPIN = 2
NDIM = NORB * NSPIN


def coulomb_tensor(f0: float, f2: float, f4: float) -> np.ndarray:
    slater = {0: f0, 2: f2, 4: f4}
    mvals = range(-2, 3)
    return np.array([[[[tensor(2, a, b, c, d, slater)
                        for d in mvals] for c in mvals]
                      for b in mvals] for a in mvals], dtype=complex)


def hermitian(x: np.ndarray) -> np.ndarray:
    return (x + x.conj().T) * 0.5


def interaction(p: np.ndarray, t: np.ndarray) -> float:
    """E_HF = 1/2 sum T_abcd (P_ba P_dc - P_da P_bc), spin indices explicit."""
    e = 0j
    for a in range(NORB):
        for b in range(NORB):
            for c in range(NORB):
                for d in range(NORB):
                    tabcd = t[a, b, c, d]
                    for s in range(NSPIN):
                        for u in range(NSPIN):
                            e += 0.5 * tabcd * (
                                p[s*NORB+b, s*NORB+a] * p[u*NORB+d, u*NORB+c]
                                - p[s*NORB+a, u*NORB+d] * p[u*NORB+c, s*NORB+b])
    if abs(e.imag) > 2e-10:
        raise AssertionError(f"Hermitian P produced complex interaction energy {e}")
    return float(e.real)


def fll(p: np.ndarray, u: float, j: float) -> tuple[float, np.ndarray]:
    """Spin-density FLL: D_st=sum_a P_(a s,a t), with covariant spin trace."""
    d = np.array([[sum(p[s*NORB+a, t*NORB+a] for a in range(NORB))
                   for t in range(NSPIN)] for s in range(NSPIN)], dtype=complex)
    n = float(np.trace(d).real)
    edc = 0.5*u*n*(n-1.0) - 0.5*j*(np.trace(d @ d).real-n)
    # dE_DC/dP_(a s,b t) = delta_ab [(U(N-1/2)+J/2) I - J D]_(t s)
    spin_v = (u*(n-0.5)+0.5*j)*np.eye(2) - j*d
    vdc = np.zeros_like(p)
    for a in range(NORB):
        for s in range(2):
            for t in range(2):
                vdc[s*NORB+a, t*NORB+a] = spin_v[s, t]
    return float(edc), hermitian(vdc)


def energy_potential(p: np.ndarray, t: np.ndarray, u: float, j: float):
    """Return E_HF, E_DC, E_Hub, V_Hub; gradient convention dE=ReTr(V dP)."""
    eint = interaction(p, t)
    edc, vdc = fll(p, u, j)
    # Differentiate the independently coded second-quantized energy with a
    # symmetric polarization identity, avoiding a hand-coded tensor gradient.
    # For a quadratic functional, E(P+D)-E(P-D) isolates exactly dE[ D ].
    vhf = np.zeros_like(p)
    for i in range(NDIM):
        for k in range(i, NDIM):
            d = np.zeros_like(p)
            d[i, k] = 1.0
            if i != k:
                d[k, i] = 1.0
            vhf[i, k] = (interaction(p+d, t)-interaction(p-d, t))/4.0
            if i != k:
                d[i, k] = 1j
                d[k, i] = -1j
                # ReTr(V dP) for this direction is -2 Im(V_ik).
                imag_response = (interaction(p+d, t)-interaction(p-d, t))/4.0
                vhf[i, k] += 1j * imag_response
                vhf[k, i] = vhf[i, k].conjugate()
            else:
                vhf[i, i] = 2.0*vhf[i, i].real
    vhf = hermitian(vhf)
    return eint, edc, eint-edc, vhf-vdc


def random_density(rng: np.random.Generator, rank_one: bool = False) -> np.ndarray:
    z = rng.normal(size=(NDIM, NDIM)) + 1j*rng.normal(size=(NDIM, NDIM))
    q, _ = np.linalg.qr(z)
    if rank_one:
        occ = np.zeros(NDIM)
        occ[0] = 1.0
    else:
        occ = np.array([.08, .17, .29, .38, .51, .62, .71, .79, .88, .94])
    return hermitian((q*occ) @ q.conj().T)


def check_fd(p, t, u, j, seed=91):
    rng = np.random.default_rng(seed)
    v = energy_potential(p, t, u, j)[3]
    z = rng.normal(size=p.shape) + 1j*rng.normal(size=p.shape)
    delta = hermitian(z)
    delta /= np.linalg.norm(delta)
    slope = float(np.trace(v @ delta).real)
    errors = []
    for h in (1e-3, 1e-4, 1e-5):
        ep = energy_potential(hermitian(p+h*delta), t, u, j)[2]
        em = energy_potential(hermitian(p-h*delta), t, u, j)[2]
        fd = (ep-em)/(2*h)
        errors.append(abs(fd-slope))
    return slope, errors


def main():
    rng = np.random.default_rng(20261014)
    u, j = 2.3, 0.41
    f2 = 14*j/1.625
    f4 = 0.625*f2
    t = coulomb_tensor(u, f2, f4)
    p = random_density(rng)
    e0, dc, hub, v = energy_potential(p, t, u, j)
    assert np.max(np.abs(p-p.conj().T)) < 1e-14

    # Full spinor derivatives, including nonzero ↑↓/↓↑ density coherences.
    offspin = p[:NORB, NORB:]
    assert np.linalg.norm(offspin) > 1e-3
    slope, fd_errors = check_fd(p, t, u, j)
    assert fd_errors[-1] < 2e-8, fd_errors
    assert max(fd_errors) < 5e-9, fd_errors

    # Exact J=0 identity: arbitrary spinor P, EHub=U/2 Tr(P-P²), V=U(1/2 I-P).
    t0 = coulomb_tensor(u, 0.0, 0.0)
    _, dc0, hub0, v0 = energy_potential(p, t0, u, 0.0)
    hub0_ref = 0.5*u*np.trace(p-p@p).real
    v0_ref = u*(0.5*np.eye(NDIM)-p)
    assert abs(dc0-0.5*u*np.trace(p)*(np.trace(p).real-1)) < 2e-10
    assert abs(hub0-hub0_ref) < 2e-10
    assert np.max(np.abs(v0-v0_ref)) < 2e-10

    # A rank-one spinor cancels its HF self-interaction. At J=0 the FLL term
    # also vanishes; for J>0 the chosen spin-density FLL can leave a remainder
    # for an entangled spinor (reported below, not silently altered).
    p1 = random_density(rng, rank_one=True)
    rank_hf = interaction(p1, t)
    _, rank_dc0, rank_hub0, _ = energy_potential(p1, t0, u, 0.0)
    assert abs(rank_hf) < 2e-10 and abs(rank_dc0) < 2e-10 and abs(rank_hub0) < 2e-10
    rank_dcj, _ = fll(p1, u, j)

    # Collinear block-diagonal reduction to the established two-spin formula.
    pu = p.copy()
    pu[:NORB, NORB:] = 0
    pu[NORB:, :NORB] = 0
    ec_full = interaction(pu, t)
    ec_blocks = 0j
    for a in range(NORB):
        for b in range(NORB):
            for c in range(NORB):
                for d in range(NORB):
                    for s in range(NSPIN):
                        for q in range(NSPIN):
                            ps = pu[s*NORB:(s+1)*NORB, s*NORB:(s+1)*NORB]
                            pq = pu[q*NORB:(q+1)*NORB, q*NORB:(q+1)*NORB]
                            ec_blocks += .5*t[a,b,c,d] * ps[b,a] * pq[d,c]
                            if s == q:
                                ec_blocks -= .5*t[a,b,c,d] * ps[d,a] * ps[b,c]
    assert abs(ec_full-ec_blocks.real) < 2e-12 and abs(ec_blocks.imag) < 2e-12
    dcc, _ = fll(pu, u, j)
    nu = np.trace(pu[:NORB, :NORB]).real
    nd = np.trace(pu[NORB:, NORB:]).real
    dc_collinear = .5*u*(nu+nd)*(nu+nd-1)-.5*j*(nu*(nu-1)+nd*(nd-1))
    assert abs(dcc-dc_collinear) < 2e-12

    # Global spin SU(2) covariance with SOC off.
    a, b = rng.normal(size=2) + 1j*rng.normal(size=2)
    s = np.array([[a, b], [-b.conjugate(), a.conjugate()]])
    s /= np.sqrt(np.linalg.det(s).real)
    rot = np.kron(s, np.eye(NORB))
    pr = hermitian(rot @ p @ rot.conj().T)
    er = energy_potential(pr, t, u, j)
    assert abs(er[0]-e0) < 3e-11
    assert abs(er[1]-dc) < 3e-11
    assert np.max(np.abs(er[3]-rot@v@rot.conj().T)) < 3e-10

    # Orbital basis relabeling transforms P and all four tensor slots together.
    perm = np.array([2, 4, 0, 3, 1])
    c = np.eye(NORB)[:, perm]
    co = np.kron(np.eye(2), c)
    tr = t[np.ix_(perm, perm, perm, perm)]
    po = hermitian(co.conj().T @ p @ co)
    eo = energy_potential(po, tr, u, j)
    assert abs(eo[0]-e0) < 3e-10
    assert abs(eo[1]-dc) < 3e-11
    assert np.max(np.abs(eo[3]-co.conj().T@v@co)) < 3e-9

    print(f"d-shell spinor: Eint={e0:.12g}, EDC={dc:.12g}, EHub={hub:.12g}")
    print(f"complex spin coherence norm={np.linalg.norm(offspin):.12g}; FD slope={slope:.12g}; errors h=1e-3,1e-4,1e-5: {fd_errors}")
    print(f"J=0 Dudarev residual energy={abs(hub0-hub0_ref):.3e}, potential={np.max(np.abs(v0-v0_ref)):.3e}")
    print(f"rank-one HF/J=0 residuals: Eint={rank_hf:.3e}, EDC={rank_dc0:.3e}, EHub={rank_hub0:.3e}; J>0 spin-FLL EDC remainder={rank_dcj:.12g}")
    print(f"SU(2) energy/potential covariance passed; orbital relabeling energy/potential covariance passed")


if __name__ == "__main__":
    main()
